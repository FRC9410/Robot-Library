    }

    $lines += "  }"
    $lines += "}"

    Set-Content -Path $outputFile -Value ($lines -join "`n") -Encoding ascii
    return $outputFile
}

function Update-BindingsFromJson {
    param(
        [Parameter(Mandatory = $true)][string]$BindingJsonPath,
        [Parameter(Mandatory = $true)][string]$SubsystemJsonPath
    )

    $subsystemDocument = Read-SubsystemDocument $SubsystemJsonPath
    $bindingDocument = Read-BindingDocument $BindingJsonPath
    $subsystems = @($subsystemDocument.subsystems)
    $bindings = @($bindingDocument.bindings)

    $constantsBySubsystemId = @{}
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $constantsBySubsystemId[$metadata.Id] = @()
    }

    $collectConstants = {
        param($Command)

        $kind = Get-BindingCommandKind $Command
        if ($kind -ne "function") {
            if ($kind -eq "wait") {
                $subsystemId = (Get-JsonPropertyValue $Command "subsystemId" "").ToString()
                $subsystem = Find-SubsystemById $subsystems $subsystemId
                $constantProperty = Get-JsonPropertyValue $Command "constantName"
                if ([string]::IsNullOrWhiteSpace($constantProperty)) {
                    throw "Wait command needs a constant name."
                }
                $value = Get-JsonPropertyValue $Command "value"
                if ($null -eq $value) {
                    throw "Wait command needs a value."
                }

                $metadata = Get-SubsystemMetadata $subsystem
                $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
                $constantsBySubsystemId[$metadata.Id] += "  public static final double $constantName = $(Format-JavaDoubleLiteral $value);"
                return
            }
            foreach ($child in @(Get-JsonPropertyValue $Command "children" @())) {
                & $collectConstants $child
            }
            return
        }

        $subsystemId = (Get-JsonPropertyValue $Command "subsystemId" "").ToString()
        $method = (Get-JsonPropertyValue $Command "method" "").ToString()
        $subsystem = Find-SubsystemById $subsystems $subsystemId
        if (-not (Get-BindingMethodNeedsValue $subsystem $method)) {
            return
        }
        $constantProperty = Get-JsonPropertyValue $Command "constantName"
        if ([string]::IsNullOrWhiteSpace($constantProperty)) {
            throw "Binding command '$method' for subsystem '$($subsystem.name)' needs a constant name."
        }
        $value = Get-JsonPropertyValue $Command "value"
        if ($null -eq $value) {
            throw "Binding command '$method' for subsystem '$($subsystem.name)' needs a value."
        }

        $metadata = Get-SubsystemMetadata $subsystem
        $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
        $constantsBySubsystemId[$metadata.Id] += "  public static final double $constantName = $(Format-JavaDoubleLiteral $value);"
    }

    foreach ($binding in $bindings) {
        foreach ($command in @(Get-JsonPropertyValue $binding "commands" @())) {
            & $collectConstants $command
        }
    }

    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $constantsFile = Join-Path $constantsDir "$($metadata.PascalName)Constants.java"
        if (-not (Test-Path $constantsFile)) {
            throw "Missing $constantsFile. Run subsystem update before binding update."
        }
        Rewrite-BindingConstantsBlock $constantsFile @($constantsBySubsystemId[$metadata.Id] | Select-Object -Unique)
    }

    $written = Write-PowerButtonBindingsFile $bindings $subsystems
    Save-BindingDocument $BindingJsonPath $bindingDocument
    Write-Host "Generated $written"
    Write-Host "Updated PowerButtonBindings.java and binding constants from $BindingJsonPath"
}

