import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readTuningSession, saveTuningSession } from "../dist-electron/tuningSessionFiles.js";
import { isTuningSessionValue } from "../dist-electron/tuningSession.js";
const directory = fileURLToPath(new URL("../../build/", import.meta.url));
const fixture = await fs.mkdtemp(path.join(directory, "tuning-session-check-"));
const connection = { targetId: "sim-localhost", host: "localhost", port: 5810 };
const robot = path.join(fixture, "robot");
const userData = path.join(fixture, "user-data");
const kp = { name: "/PowerLib/Subsystems/Intake/Variables/PID/kP", type: "double", value: 2.5 };
const first = await saveTuningSession(userData, robot, connection, [kp]);
const restarted = await import(`../dist-electron/tuningSessionFiles.js?restart=${Date.now()}`);
assert.deepEqual((await restarted.readTuningSession(userData, robot, connection)).values, [kp]);
await Promise.all([saveTuningSession(userData, robot, connection, [{ ...kp, name: kp.name.replace("kP", "kI"), value: 0.2 }]), saveTuningSession(userData, robot, connection, [{ ...kp, value: 3.5 }])]);
assert.equal((await readTuningSession(userData, robot, connection)).values.length, 2);
for (const target of [{ ...connection, targetId: "other" }, { ...connection, host: "10.94.10.2" }, { ...connection, port: 5811 }]) assert.deepEqual((await readTuningSession(userData, robot, target)).values, []);
assert.deepEqual((await readTuningSession(userData, path.join(fixture, "other-robot"), connection)).values, []);
for (const invalid of [{ ...kp, value: NaN }, { ...kp, type: "int", value: 1.2 }, { ...kp, name: "/PowerLib/Tuning/RequestedEnabled" }, { ...kp, name: "/PowerLib/Characterization/Run" }]) assert.equal(isTuningSessionValue(invalid), false);
await fs.writeFile(first.path, "{broken");
await assert.rejects(saveTuningSession(userData, robot, connection, [kp]));
assert.equal(await fs.readFile(first.path, "utf8"), "{broken");
console.log("Temporary tuning recovery checks passed: disk restart, concurrent merge, project/profile/endpoint isolation, control exclusion and corrupt-file preservation.");
