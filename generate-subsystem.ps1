                Remove-Item -LiteralPath $outputFile -Force
                Write-Host "Deleted removed game piece sim constants GamePieceSimConstants.java"
            }
        }
        return $null
    }

    New-Item -ItemType Directory -Force -Path $simConstantsDir | Out-Null

    $lines = @(
        "package frc.robot.constants.sim;",
        "",
        "// Generated by PowerLib simulation tool. Edit powerlib-sim-config.json, then run update.",
        "",
        "public class GamePieceSimConstants {"
    )

    foreach ($gamePiece in $gamePieces) {
        $name = Get-ObjectPropertyValue $gamePiece "name" "GamePiece"
        $prefix = Convert-ToJavaConstantName $name
        $lines += "  public static final String $($prefix)_NAME = $(Format-JavaStringLiteral $name);"
        $lines += "  public static final double $($prefix)_MASS_KG = $(Format-JavaDoubleLiteral (Get-ObjectPropertyValue $gamePiece "massKg" 0.25));"
        $lines += "  public static final double $($prefix)_DIAMETER_METERS = $(Format-JavaDoubleLiteral (Get-ObjectPropertyValue $gamePiece "diameterMeters" 0.18));"
        $lines += "  public static final double $($prefix)_LINEAR_DAMPING = $(Format-JavaDoubleLiteral (Get-ObjectPropertyValue $gamePiece "linearDamping" 0.1));"
        $lines += "  public static final double $($prefix)_ANGULAR_DAMPING = $(Format-JavaDoubleLiteral (Get-ObjectPropertyValue $gamePiece "angularDamping" 0.1));"
        $lines += "  public static final double $($prefix)_FRICTION_COEFFICIENT = $(Format-JavaDoubleLiteral (Get-ObjectPropertyValue $gamePiece "frictionCoefficient" 0.8));"
        $lines += "  public static final double $($prefix)_RESTITUTION_COEFFICIENT = $(Format-JavaDoubleLiteral (Get-ObjectPropertyValue $gamePiece "restitutionCoefficient" 0.3));"
        $lines += ""
    }

    $lines += "}"
    Set-Content -Path $outputFile -Value ($lines -join "`r`n") -Encoding ascii
    return $outputFile
}

function Get-GamePiecesFromSimConfig {
    param([Parameter(Mandatory = $true)][string]$SimConfigJsonPath)

    if (-not (Test-Path $SimConfigJsonPath)) {
        return @()
    }

    $raw = Get-Content -Path $SimConfigJsonPath -Raw -Encoding utf8
    $parsed = $raw | ConvertFrom-Json
    $cfg = if (($parsed.PSObject.Properties.Name -contains "config") -and $null -ne $parsed.config) { $parsed.config } else { $parsed }
    if (-not ($cfg.PSObject.Properties.Name -contains "gamePieces") -or $null -eq $cfg.gamePieces) {
        return @()
    }

    return @($cfg.gamePieces)
}

function Get-SimConstantClassName {
    param([Parameter(Mandatory = $true)]$Metadata)
    return "frc.robot.constants.sim.$($Metadata.PascalName)SimConstants"
}

function Get-SimMemberPrefix {
    param([Parameter(Mandatory = $true)]$Metadata)
    return Convert-ToJavaIdentifier $Metadata.Name "simSubsystem"
}

function New-GamePieceInfoCaseLines {
    param([AllowEmptyCollection()]$GamePieces = @())

    $lines = @()
    foreach ($gamePiece in @($GamePieces)) {
        if ($null -eq $gamePiece) {
            continue
        }
        $name = Get-ObjectPropertyValue $gamePiece "name" "GamePiece"
        $prefix = Convert-ToJavaConstantName $name
        $lines += "    if (frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_NAME.equals(gamePieceType)) {"
        $lines += "      return new GamePieceOnFieldSimulation.GamePieceInfo("
        $lines += "          frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_NAME,"
        $lines += "          Geometry.createCircle(frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_DIAMETER_METERS / 2.0),"
        $lines += "          Meters.of(frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_DIAMETER_METERS),"
        $lines += "          Kilograms.of(frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_MASS_KG),"
        $lines += "          frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_LINEAR_DAMPING,"
        $lines += "          frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_ANGULAR_DAMPING,"
        $lines += "          frc.robot.constants.sim.GamePieceSimConstants.$($prefix)_RESTITUTION_COEFFICIENT);"
        $lines += "    }"
    }

    return $lines
}

function Rewrite-PowerSimManagerBlock {
    param(
        [Parameter(Mandatory = $true)][string]$PowerSimManagerPath,
        [Parameter(Mandatory = $true)]$Subsystems,
        [Parameter(Mandatory = $true)][string]$SimConfigJsonPath
    )

    if (-not (Test-Path $PowerSimManagerPath)) {
        return
    }

    $simConfig = Read-SimConfigDocument $SimConfigJsonPath
    $fields = @()
    $init = @()
    $periodic = @()
    $methods = @()

    foreach ($subsystem in @($Subsystems)) {
        $metadata = Get-SubsystemMetadata $subsystem
        $config = Get-SimConfigForSubsystem $simConfig $metadata.Id
        $type = Get-SimConfigType $config
        if ($type -eq "none") {
            continue
        }

        $member = Get-SimMemberPrefix $metadata
        $constantsClass = Get-SimConstantClassName $metadata

        if ($type -eq "intake") {
            $fields += "  private IntakeSimulation $($member)IntakeSimulation;"
            $fields += "  private boolean $($member)IntakeRequested = false;"
            $fields += "  private final BooleanSubscriber $($member)IntakeRunningSubscriber ="
            $fields += "      simTable.getBooleanTopic(`"$($metadata.PascalName)/IntakeRunning`").subscribe(false);"
            $fields += "  private final IntegerPublisher $($member)HeldPublisher ="
            $fields += "      simTable.getIntegerTopic(`"$($metadata.PascalName)/Held`").publish();"

            $init += "    $($member)IntakeSimulation ="
            $init += "        createIntakeSimulation("
            $init += "            $constantsClass.GAME_PIECE_TYPE,"
            $init += "            $constantsClass.INTAKE_KIND,"
            $init += "            $constantsClass.INTAKE_SIDE,"
            $init += "            $constantsClass.INTAKE_WIDTH_METERS,"
            $init += "            $constantsClass.INTAKE_EXTENSION_METERS,"
            $init += "            $constantsClass.INTAKE_CAPACITY);"

            $periodic += "    updateIntakeControl("
            $periodic += "        $($member)IntakeSimulation,"
            $periodic += "        $($member)IntakeRequested,"
            $periodic += "        $($member)IntakeRunningSubscriber,"
            $periodic += "        $($member)HeldPublisher);"

            $methods += "  public void start$($metadata.PascalName)Intake() {"
            $methods += "    $($member)IntakeRequested = true;"
            $methods += "  }"
            $methods += ""
            $methods += "  public void stop$($metadata.PascalName)Intake() {"
            $methods += "    $($member)IntakeRequested = false;"
            $methods += "  }"
            $methods += ""
            $methods += "  public boolean obtain$($metadata.PascalName)GamePiece() {"
            $methods += "    return $($member)IntakeSimulation != null && $($member)IntakeSimulation.obtainGamePieceFromIntake();"
            $methods += "  }"
            $methods += ""
            $methods += "  public int get$($metadata.PascalName)GamePiecesAmount() {"
            $methods += "    return $($member)IntakeSimulation == null ? 0 : $($member)IntakeSimulation.getGamePiecesAmount();"
            $methods += "  }"
        } elseif ($type -eq "projectile") {
            $fields += "  private boolean $($member)LaunchWasRequested = false;"
            $fields += "  private final BooleanSubscriber $($member)LaunchSubscriber ="
            $fields += "      simTable.getBooleanTopic(`"$($metadata.PascalName)/Launch`").subscribe(false);"

            $periodic += "    boolean $($member)LaunchRequested = $($member)LaunchSubscriber.get();"
            $periodic += "    if ($($member)LaunchRequested && !$($member)LaunchWasRequested) {"
            $periodic += "      launch$($metadata.PascalName)Projectile();"
            $periodic += "    }"
            $periodic += "    $($member)LaunchWasRequested = $($member)LaunchRequested;"

            $methods += "  public void launch$($metadata.PascalName)Projectile() {"
            $methods += "    launchProjectile("
            $methods += "        $constantsClass.GAME_PIECE_TYPE,"
            $methods += "        new Translation2d($constantsClass.SHOOTER_OFFSET_X_METERS, $constantsClass.SHOOTER_OFFSET_Y_METERS),"
            $methods += "        $constantsClass.LAUNCH_HEIGHT_METERS,"
            $methods += "        $constantsClass.LAUNCH_SPEED_METERS_PER_SECOND,"
            $methods += "        $constantsClass.LAUNCH_ANGLE_DEGREES,"
            $methods += "        new Translation3d($constantsClass.TARGET_X_METERS, $constantsClass.TARGET_Y_METERS, $constantsClass.TARGET_Z_METERS),"
            $methods += "        new Translation3d("
            $methods += "            $constantsClass.TARGET_TOLERANCE_X_METERS,"
            $methods += "            $constantsClass.TARGET_TOLERANCE_Y_METERS,"
            $methods += "            $constantsClass.TARGET_TOLERANCE_Z_METERS),"
            $methods += "        $constantsClass.BECOMES_GAME_PIECE_ON_GROUND);"
            $methods += "  }"
        }
    }

    $gamePieceInfoLines = New-GamePieceInfoCaseLines (Get-GamePiecesFromSimConfig $SimConfigJsonPath)

    $content = Get-Content -Path $PowerSimManagerPath -Raw
    $content = Replace-MarkedBlock $content $SimFieldsStartMarker $SimFieldsEndMarker $fields
    $content = Replace-MarkedBlock $content $SimInitStartMarker $SimInitEndMarker $init
    $content = Replace-MarkedBlock $content $SimPeriodicStartMarker $SimPeriodicEndMarker $periodic
    $content = Replace-MarkedBlock $content $GamePieceInfoStartMarker $GamePieceInfoEndMarker $gamePieceInfoLines
    $content = Replace-MarkedBlock $content $SimMethodsStartMarker $SimMethodsEndMarker $methods
    Set-Content -Path $PowerSimManagerPath -Value $content -Encoding ascii
}

function Update-SubsystemsFromJson {
    param([Parameter(Mandatory = $true)][string]$JsonPath)

    $document = Read-SubsystemDocument $JsonPath
    $subsystems = @($document.subsystems)

    $constantsBarrel = Join-Path (Get-Location) "src/main/java/frc/robot/Constants.java"
    if (-not (Test-Path $constantsBarrel)) {
        throw "Missing src/main/java/frc/robot/Constants.java. Run robotLibraryInstall first."
    }

    $stateMachineFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/StateMachine.java"
    if (-not (Test-Path $stateMachineFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/StateMachine.java. Run robotLibraryInstall first."
    }

    $powerDashboardFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/PowerDashboard.java"
    if (-not (Test-Path $powerDashboardFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/PowerDashboard.java. Run robotLibraryInstall first."
    }
    $powerSimManagerFile = Join-Path (Get-Location) "src/main/java/frc/robot/simulation/PowerSimManager.java"

    $written = @()
    $characterizationWritten = @()
    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    $customBlocksById = Get-CustomConstantsBySubsystemId $constantsDir
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $written += Write-ConstantsFile $subsystem $metadata $customBlocksById
        $characterizationFile = Write-CharacterizationFile $subsystem $metadata
        if ($null -ne $characterizationFile) {
            $characterizationWritten += $characterizationFile
        }
    }

    Rewrite-ConstantsBlock $constantsBarrel $subsystems
    Rewrite-StateMachineBlock $stateMachineFile $subsystems
    Rewrite-PowerDashboardCharacterizationBlock $powerDashboardFile $subsystems
    Rewrite-PowerSimManagerBlock $powerSimManagerFile $subsystems $SimConfigJson
    Remove-DeletedGeneratedFiles $subsystems
    Remove-StaleCharacterizationFiles $subsystems
    Save-SubsystemDocument $JsonPath $document

    foreach ($file in $written) {
        Write-Host "Generated $file"
    }
    foreach ($file in $characterizationWritten) {
        Write-Host "Generated $file"
    }
    Write-Host "Updated Constants.java, StateMachine.java, and PowerDashboard.java from $JsonPath"
}

function Invoke-BuildIfNeeded {
    if ($SkipBuild) {
        return
    }

    $isWindowsHost = [System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT
    $gradlew = if ($isWindowsHost) { ".\gradlew.bat" } else { "./gradlew" }
    if (Test-Path $gradlew) {
        & $gradlew --no-daemon --console=plain build
        if ($LASTEXITCODE -ne 0) {
            exit $LASTEXITCODE
        }
    } else {
        Write-Host "Skipped build because no Gradle wrapper was found."
    }
}

if ($UpdateSubsystems -or $UpdateBindings) {
    if ($UpdateSubsystems) {
        Update-SubsystemsFromJson $SubsystemsJson
        Write-SimConstantsFile $SimConfigJson
        $gamePieceSimFile = Write-GamePieceSimConstantsFile $SimConfigJson
        if ($null -ne $gamePieceSimFile) {
            Write-Host "Generated $gamePieceSimFile"
        }
        $simWritten = Write-SubsystemSimConstantsFiles $SimConfigJson (Read-SubsystemDocument $SubsystemsJson).subsystems
        foreach ($file in $simWritten) {
            Write-Host "Generated $file"
        }
    }
    if ($UpdateBindings) {
        Update-BindingsFromJson $BindingsJson $SubsystemsJson
    }
    Invoke-BuildIfNeeded
    exit 0
}

