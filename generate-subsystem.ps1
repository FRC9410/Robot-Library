        [Parameter(Mandatory = $true)][string[]]$Path,
        [Parameter(Mandatory = $true)]$DefaultValue
    )

    $current = $SwerveConfig
    foreach ($segment in $Path) {
        $property = Get-ObjectProperty $current $segment
