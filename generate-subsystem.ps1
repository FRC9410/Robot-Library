    return "$(Get-BindingControllerExpression $Controller).$InputName($threshold)"
}

function Get-BindingEventName {
    param([Parameter(Mandatory = $true)][string]$Event)

    $accepted = @("onTrue", "onFalse", "whileTrue", "toggleOnTrue")
    if (-not ($accepted -contains $Event)) {
        throw "Unsupported binding event '$Event'. Accepted values: $($accepted -join ', ')."
    }

    return $Event
}

function Ensure-BindingConstantsMarkers {
    param([Parameter(Mandatory = $true)][string]$ConstantsPath)

    $content = Get-Content -Path $ConstantsPath -Raw
    if ($content.Contains($BindingConstantsStartMarker) -and $content.Contains($BindingConstantsEndMarker)) {
        return
    }

    $insertAt = $content.IndexOf($CustomConstantsStartMarker)
    if ($insertAt -lt 0) {
        $insertAt = $content.LastIndexOf("}")
    }
    if ($insertAt -lt 0) {
        throw "Could not find a place to insert binding constants in $ConstantsPath."
    }

    $markers = "$BindingConstantsStartMarker`n$BindingConstantsEndMarker`n`n"
    $updated = $content.Substring(0, $insertAt).TrimEnd() + "`n`n$markers" + $content.Substring($insertAt)
    Set-Content -Path $ConstantsPath -Value $updated -Encoding ascii
}

function Rewrite-BindingConstantsBlock {
    param(
        [Parameter(Mandatory = $true)][string]$ConstantsPath,
        [Parameter(Mandatory = $true)][string[]]$Entries
    )

    Ensure-BindingConstantsMarkers $ConstantsPath
    $content = Get-Content -Path $ConstantsPath -Raw
    $start = $content.IndexOf($BindingConstantsStartMarker) + $BindingConstantsStartMarker.Length
    $end = $content.IndexOf($BindingConstantsEndMarker)
    $block = if ($Entries.Count -eq 0) { "`n" } else { "`n" + ($Entries -join "`n") + "`n" }
    $updated = $content.Substring(0, $start) + $block + $content.Substring($end)
    Set-Content -Path $ConstantsPath -Value $updated -Encoding ascii
}

function Get-BindingCommandKind {
    param([Parameter(Mandatory = $true)]$Command)

    $kind = (Get-JsonPropertyValue $Command "kind" "function").ToString()
    if ($kind -eq "sequence" -or $kind -eq "parallel" -or $kind -eq "parallelRace" -or $kind -eq "function" -or $kind -eq "wait") {
        return $kind
    }

    return "function"
}

function New-InstantBindingCommandCall {
    param(
        [Parameter(Mandatory = $true)]$Command,
        [Parameter(Mandatory = $true)]$Subsystems
    )

    $subsystemId = (Get-JsonPropertyValue $Command "subsystemId" "").ToString()
    $method = (Get-JsonPropertyValue $Command "method" "").ToString()
    $subsystem = Find-SubsystemById $Subsystems $subsystemId
    $metadata = Get-SubsystemMetadata $subsystem
    $needsValue = Get-BindingMethodNeedsValue $subsystem $method
    $argument = ""
    if ($needsValue) {
        $constantProperty = Get-JsonPropertyValue $Command "constantName"
        if ([string]::IsNullOrWhiteSpace($constantProperty)) {
            throw "Binding command '$method' for subsystem '$($metadata.Name)' needs a constant name."
        }
        $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
        $argument = "Constants.$($metadata.PascalName).$constantName"
    }

    $call = if ($needsValue) {
        "stateMachine.$($metadata.CamelName).$method($argument);"
    } else {
        "stateMachine.$($metadata.CamelName).$method();"
    }

    return [pscustomobject]@{
        Call = $call
        Requirement = "stateMachine.$($metadata.CamelName)"
    }
}

