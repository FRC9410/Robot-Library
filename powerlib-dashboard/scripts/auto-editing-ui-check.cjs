const assert = require('node:assert/strict');
const fs = require('node:fs');

exports.checkEditingUI = async ({ window, evaluate, click, wait, saved, selectStep, selectOption, fill, screenshot, readDoc, jsonPath, generatedPath, reloadApp }) => {
  const original = fs.readFileSync(jsonPath, 'utf8'), originalJava = fs.readFileSync(generatedPath, 'utf8');
  const edit = async label => {
    if(label==='Undo'||label==='Redo') await evaluate(`document.querySelector('[aria-label="${label} auto edit"]').click()`);
    else { const action={Copy:{key:'c',ctrlKey:true},Paste:{key:'v',ctrlKey:true},'Move down':{key:'ArrowDown',altKey:true}}[label];
      await evaluate(`document.querySelector('svg[aria-label="Field and robot position"]').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,cancelable:true,...${JSON.stringify(action)}}))`); }
    await new Promise(resolve=>setTimeout(resolve,50));
  };
  const key = async (key, options = {}) => { await evaluate(`document.querySelector('svg[aria-label="Field and robot position"]').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,cancelable:true,key:${JSON.stringify(key)},...${JSON.stringify(options)}}))`); await new Promise(resolve => setTimeout(resolve, 50)); };
  const first = () => readDoc().autos[0].steps[0];
  await selectStep(0); await key('ArrowRight'); await saved(); assert.equal(first().x, 1.55);
  await evaluate(`document.querySelector('svg[aria-label="Field and robot position"]').focus()`);
  window.webContents.sendInputEvent({type:'keyDown',keyCode:'Z',modifiers:['control']});
  window.webContents.sendInputEvent({type:'keyUp',keyCode:'Z',modifiers:['control']});
  await wait(() => evaluate(`[...document.querySelectorAll('input')].find(el=>el.labels?.[0]?.textContent==='X (m)').value==='1.5'`));
  await saved(); assert.equal(first().x, 1.5, 'Native Ctrl Z reaches document history');
  window.webContents.sendInputEvent({type:'keyDown',keyCode:'Z',modifiers:['control','shift']});
  window.webContents.sendInputEvent({type:'keyUp',keyCode:'Z',modifiers:['control','shift']});
  await wait(() => evaluate(`[...document.querySelectorAll('input')].find(el=>el.labels?.[0]?.textContent==='X (m)').value==='1.55'`));
  await saved(); assert.equal(first().x,1.55,'Native Ctrl Shift Z redoes the document edit');
  window.webContents.sendInputEvent({type:'keyDown',keyCode:'Z',modifiers:['control']});
  window.webContents.sendInputEvent({type:'keyUp',keyCode:'Z',modifiers:['control']});
  await wait(() => evaluate(`[...document.querySelectorAll('input')].find(el=>el.labels?.[0]?.textContent==='X (m)').value==='1.5'`));
  await saved();
  await edit('Redo'); await saved(); assert.equal(first().x, 1.55);
  await edit('Undo'); await saved(); assert.equal(first().x, 1.5);
  const before = readDoc().autos[0].steps.length;
  await evaluate(`document.querySelector('[aria-label="Auto steps"]').children[1].querySelector('.MuiListItemButton-root').dispatchEvent(new MouseEvent('click',{bubbles:true,shiftKey:true}))`);
  assert.equal(await evaluate(`document.querySelectorAll('[aria-label="Auto steps"] .Mui-selected').length`), 2);
  await key('ArrowUp'); await saved(); assert.deepEqual(readDoc().autos[0].steps.slice(0,2).map(step => step.y), [2.05,2.05]);
  await edit('Undo'); await saved();
  await edit('Copy'); await edit('Paste'); await saved();
  assert.equal(readDoc().autos[0].steps.length, before + 2);
  assert.equal(new Set(readDoc().autos[0].steps.map(step=>step.id)).size, before + 2);
  await edit('Undo'); await saved(); assert.equal(readDoc().autos[0].steps.length, before);
  await key('Escape'); await selectStep(0);
  const order = readDoc().autos[0].steps.map(step => step.id);
  await edit('Move down'); await saved(); assert.equal(readDoc().autos[0].steps[1].id, order[0]);
  await edit('Undo'); await saved(); assert.deepEqual(readDoc().autos[0].steps.map(step=>step.id),order);
  await evaluate(`document.querySelector('[aria-label="Auto steps"]').children[1].querySelector('.MuiListItemButton-root').dispatchEvent(new MouseEvent('click',{bubbles:true,shiftKey:true}))`);
  const position = async (x,y) => evaluate(`(()=>{const svg=document.querySelector('svg[aria-label="Field and robot position"]'),length=Number(svg.dataset.fieldLength),width=Number(svg.dataset.fieldWidth),p=new DOMPoint(${x}/length*(480*length/width),480-${y}/width*480).matrixTransform(svg.getScreenCTM());return {x:Math.round(p.x),y:Math.round(p.y)};})()`);
  const start = await position(1.5,2), target = await position(2,2.5);
  window.webContents.sendInputEvent({type:'mouseMove',...start});
  window.webContents.sendInputEvent({type:'mouseDown',...start,button:'left',clickCount:1});
  window.webContents.sendInputEvent({type:'mouseMove',...target,modifiers:['leftButtonDown','control']});
  await wait(() => evaluate(`Number([...document.querySelectorAll('[aria-label="Auto steps"] .MuiListItemText-secondary')][0].textContent.match(/X ([\\d.]+)/)[1])>1.8`));
  await new Promise(resolve => setTimeout(resolve,700)); assert.equal(first().x,1.5,'An in-progress gesture does not autosave partial coordinates');
  window.webContents.sendInputEvent({type:'mouseUp',...target,button:'left',clickCount:1}); await saved();
  assert.ok(Math.abs(first().x-2)<.04); assert.ok(Math.abs(readDoc().autos[0].steps[1].x-first().x-2)<.001,'Group dragging keeps spacing');
  await edit('Undo'); await saved(); assert.deepEqual(readDoc().autos[0].steps.slice(0,2).map(step=>[step.x,step.y]),[[1.5,2],[3.5,2]],'A complete drag is one undo');
  await key('Escape');
  const boxStart = await position(.5,1.5), boxEnd = await position(4,2.5);
  window.webContents.sendInputEvent({type:'mouseMove',...boxStart}); window.webContents.sendInputEvent({type:'mouseDown',...boxStart,button:'left',clickCount:1});
  window.webContents.sendInputEvent({type:'mouseMove',...boxEnd,modifiers:['leftButtonDown']}); await wait(() => evaluate(`!!document.querySelector('[data-box-selection]')`));
  window.webContents.sendInputEvent({type:'mouseUp',...boxEnd,button:'left',clickCount:1});
  await wait(() => evaluate(`document.querySelectorAll('[aria-label="Auto steps"] .Mui-selected').length===2`));
  assert.equal(readDoc().autos[0].steps.length,before,'Box selection never adds points');
  await key('Escape'); await selectStep(0);
  const snapTarget = await position(3.52,1.1);
  window.webContents.sendInputEvent({type:'mouseMove',...start}); window.webContents.sendInputEvent({type:'mouseDown',...start,button:'left',clickCount:1});
  window.webContents.sendInputEvent({type:'mouseMove',...snapTarget,modifiers:['leftButtonDown']}); await wait(() => evaluate(`!!document.querySelector('[data-snap-guide]')`));
  window.webContents.sendInputEvent({type:'mouseUp',...snapTarget,button:'left',clickCount:1}); await saved(); assert.equal(first().x,3.5,'Native drag snaps to another point X');
  await edit('Undo'); await saved();
  await key('Escape'); await selectStep(0);
  // The + creates a new leg, so its source is a snap target rather than a moved point.
  const source = readDoc().autos[0].steps[2];
  for (const mode of ['vertical', 'horizontal', 'diagonal', 'bypass']) {
    await key('Escape'); await selectStep(2);
    const handle = await evaluate(`(()=>{const r=document.querySelector('[data-add-point-handle]').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)};})()`);
    const destination = await position(source.x + (mode === 'vertical' || mode === 'bypass' ? .04 : 1.4), source.y + (mode === 'horizontal' ? .04 : mode === 'diagonal' ? 1.44 : 1.4));
    const modifiers = mode === 'bypass' ? ['control'] : [];
    window.webContents.sendInputEvent({type:'mouseMove',...handle});
    window.webContents.sendInputEvent({type:'mouseDown',...handle,button:'left',clickCount:1,modifiers});
    window.webContents.sendInputEvent({type:'mouseMove',...destination,modifiers:['leftButtonDown',...modifiers]});
    await wait(() => evaluate(`!!document.querySelector('[data-new-point-preview]')`));
    assert.equal(readDoc().autos[0].steps.length,before,'Creation preview does not persist a new step');
    assert.equal(await evaluate(`!!document.querySelector('[data-snap-guide]')`),mode !== 'bypass');
    if (mode === 'diagonal') await screenshot('plus-source-snapping');
    window.webContents.sendInputEvent({type:'mouseUp',...destination,button:'left',clickCount:1,modifiers});
    await wait(() => readDoc().autos[0].steps.length === before + 1);
    await saved(); const created = readDoc().autos[0].steps[3];
    assert.equal(readDoc().autos[0].steps.length,before+1);
    assert.deepEqual(readDoc().autos[0].steps[2],source,'Source stays fixed');
    if (mode === 'vertical') assert.equal(created.x,source.x,'+ drag snaps to source X');
    if (mode === 'horizontal') assert.equal(created.y,source.y,'+ drag snaps to source Y');
    if (mode === 'diagonal') assert.ok(Math.abs((created.x-source.x)-(created.y-source.y))<.0002,'+ drag snaps to a 45° line from its source');
    if (mode === 'bypass') assert.ok(Math.abs(created.x-source.x)>.015,'Ctrl held from mouse-down bypasses source snapping');
    await edit('Undo'); await saved(); assert.equal(readDoc().autos[0].steps.length,before);
  }
  console.log('Plus drag snapping passed: source X/Y/45° alignment, Ctrl bypass from mouse-down, preview-only drafts, fixed source, insertion and undo.');
  await key('Escape'); await selectStep(0);
  const inputProtection = readDoc().autos[0].steps.length;
  await evaluate(`[...document.querySelectorAll('input')].find(el=>el.labels?.[0]?.textContent==='X (m)').dispatchEvent(new KeyboardEvent('keydown',{bubbles:true,key:'d',ctrlKey:true}))`);
  await saved(); assert.equal(readDoc().autos[0].steps.length, inputProtection, 'Typing shortcuts in inputs does not duplicate steps');
  await click('Save as named point'); await saved(); const pointId = readDoc().points[0].id;
  assert.equal(first().pointId, pointId);
  await selectStep(1); await selectOption('Named point', 'Point 1'); await saved();
  await fill('X (m)', 2.5); await saved(); assert.equal(first().x, 2.5); assert.equal(readDoc().points[0].x, 2.5);
  await click('New auto'); await fill('Auto name', 'Linked routine');
  await click('Add step'); await wait(() => evaluate(`!!document.querySelector('[role=menu]')`));
  await evaluate(`[...document.querySelectorAll('[role=menuitem]')].find(el=>el.textContent==='Add point').click()`);
  await wait(() => evaluate(`!document.querySelector('[role=menu]')`));
  await selectOption('Named point', 'Point 1'); await fill('Y (m)', 4); await saved();
  assert.deepEqual(readDoc().autos.flatMap(auto=>auto.steps.filter(step=>step.pointId===pointId).map(step=>[step.x,step.y])), [[2.5,4],[2.5,4],[2.5,4]], 'Named links update across routines');
  await selectOption('Alliance', 'Blue');
  await click('Points');
  await evaluate(`document.querySelector('[aria-label="Named points"] .MuiListItemButton-root').click()`);
  await fill('X (m)',3); await fill('Point name','Reusable spot'); await saved();
  assert.equal(readDoc().points[0].x,3,'Side editor changes shared source coordinates');
  assert.equal(await evaluate(`!!document.querySelector('[role=dialog]')`),false);
  await click('Save'); await wait(() => evaluate(`document.querySelector('[data-auto-code-current]').dataset.autoCodeCurrent==='true'`));
  assert.ok(fs.readFileSync(generatedPath,'utf8').includes('REUSABLE_SPOT'));
  await screenshot('phase4-named-point-editor');
  await click('Routines'); await selectStep(0);
  await edit('Copy');
  await click('Points'); await evaluate(`document.querySelector('[aria-label="Delete named point Reusable spot"]').click()`); await saved(); await click('Routines');
  assert.equal(readDoc().points.length,0); assert.ok(readDoc().autos.every(auto=>auto.steps.every(step=>step.type!=='drive'||step.pointId===null)));
  await edit('Paste'); await saved(); assert.equal(readDoc().autos[1].steps[1].pointId,null,'Pasting after deleting a shared point keeps coordinates without a dangling link');
  await edit('Undo'); await saved();
  // Resize through the native mouse path, then verify restoration through the real app reload.
  const divider=await evaluate(`(()=>{const el=document.querySelector('[aria-label="Resize steps pane"]'),r=el.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2),value:Number(el.getAttribute('aria-valuenow'))};})()`);
  window.webContents.sendInputEvent({type:'mouseMove',x:divider.x,y:divider.y});
  window.webContents.sendInputEvent({type:'mouseDown',x:divider.x,y:divider.y,button:'left',clickCount:1});
  window.webContents.sendInputEvent({type:'mouseMove',x:divider.x-70,y:divider.y,modifiers:['leftButtonDown']});
  window.webContents.sendInputEvent({type:'mouseUp',x:divider.x-70,y:divider.y,button:'left',clickCount:1});
  await wait(() => evaluate(`Number(document.querySelector('[aria-label="Resize steps pane"]').getAttribute('aria-valuenow'))>=${divider.value+65}`));
  await reloadApp(); assert.ok(await evaluate(`Number(document.querySelector('[aria-label="Resize steps pane"]').getAttribute('aria-valuenow'))>=${divider.value+65}`));
  await screenshot('phase4-resized');
  fs.writeFileSync(jsonPath,original); fs.writeFileSync(generatedPath,originalJava);
  await evaluate(`localStorage.removeItem('powerlib.auto.columns')`); await reloadApp();
  console.log('Phase 4 native UI passed: undo/redo, multi-selection, copy/paste, input shortcut protection, shared named points across routines, side-editor generation, unlinking, and pane resize persistence.');
};
