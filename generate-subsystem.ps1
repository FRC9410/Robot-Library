function Ensure-ConstantsMarkers {
    param([Parameter(Mandatory = $true)][string]$ConstantsPath)

    $content = Get-Content -Path $ConstantsPath -Raw
    if ($content.Contains($ConstantsStartMarker) -and $content.Contains($ConstantsEndMarker)) {
        return
    }

    $index = $content.LastIndexOf("}")
    if ($index -lt 0) {
        throw "Could not find closing brace in Constants.java."
    }

    $markers = "$ConstantsStartMarker`n$ConstantsEndMarker`n"
    $updated = $content.Substring(0, $index).TrimEnd() + "`n`n$markers}"
    Set-Content -Path $ConstantsPath -Value $updated -Encoding ascii
}

function Remove-UnmarkedGeneratedConstants {
    param([Parameter(Mandatory = $true)][string]$ConstantsPath)

    $lines = @(Get-Content -Path $ConstantsPath)
    $kept = @()
    foreach ($line in $lines) {
        $match = [regex]::Match($line, "^\s*public static final class\s+([A-Za-z0-9_]+)\s+extends\s+frc\.robot\.constants\.[A-Za-z0-9_]+Constants\s+\{\}\s*$")
        if ($match.Success -and -not ($BuiltInConstantNames -contains $match.Groups[1].Value)) {
            continue
        }
        $kept += $line
    }

    Set-Content -Path $ConstantsPath -Value ($kept -join "`n") -Encoding ascii
}

function Rewrite-ConstantsBlock {
    param(
        [Parameter(Mandatory = $true)][string]$ConstantsPath,
        [Parameter(Mandatory = $true)]$Subsystems
    )

    Ensure-ConstantsMarkers $ConstantsPath
    Remove-UnmarkedGeneratedConstants $ConstantsPath
    Ensure-ConstantsMarkers $ConstantsPath

    $content = Get-Content -Path $ConstantsPath -Raw
    $start = $content.IndexOf($ConstantsStartMarker) + $ConstantsStartMarker.Length
    $end = $content.IndexOf($ConstantsEndMarker)
    $entries = @()
    foreach ($subsystem in @($Subsystems)) {
        $metadata = Get-SubsystemMetadata $subsystem
        $entries += "  public static final class $($metadata.PascalName) extends frc.robot.constants.$($metadata.PascalName)Constants {}"
    }

    $block = if ($entries.Count -eq 0) { "" } else { "`n" + ($entries -join "`n") + "`n" }
    $updated = $content.Substring(0, $start) + $block + $content.Substring($end)
    Set-Content -Path $ConstantsPath -Value $updated -Encoding ascii
}

function Rewrite-StateMachineBlock {
    param(
        [Parameter(Mandatory = $true)][string]$StateMachinePath,
        [Parameter(Mandatory = $true)]$Subsystems
    )

    $content = Get-Content -Path $StateMachinePath -Raw
    if (-not $content.Contains($StateMachineStartMarker) -or -not $content.Contains($StateMachineEndMarker)) {
        throw "Could not find POWERLIB GENERATED SUBSYSTEMS markers in StateMachine.java. Re-run the installer or add the DO NOT DELETE markers manually."
    }

    $fields = @()
    foreach ($subsystem in @($Subsystems)) {
        $metadata = Get-SubsystemMetadata $subsystem
        $fields += "  public final $($metadata.SubsystemClassName) $($metadata.CamelName) = new $($metadata.SubsystemClassName)(Constants.$($metadata.PascalName).$($metadata.ConfigConstantName));"
    }

    $start = $content.IndexOf($StateMachineStartMarker) + $StateMachineStartMarker.Length
    $end = $content.IndexOf($StateMachineEndMarker)
    $block = if ($fields.Count -eq 0) { "`n" } else { "`n" + ($fields -join "`n") + "`n" }
    $updated = $content.Substring(0, $start) + $block + $content.Substring($end)
    Set-Content -Path $StateMachinePath -Value $updated -Encoding ascii
}

function Get-PreservedCustomConstantsBlock {
    param([Parameter(Mandatory = $true)][string]$Path)

    if (-not (Test-Path $Path)) {
        return $null
    }

    $content = Get-Content -Path $Path -Raw
    if (-not $content.Contains($CustomConstantsStartMarker) -or -not $content.Contains($CustomConstantsEndMarker)) {
        return $null
    }

    $start = $content.IndexOf($CustomConstantsStartMarker) + $CustomConstantsStartMarker.Length
    $end = $content.IndexOf($CustomConstantsEndMarker)
    return $content.Substring($start, $end - $start).Trim("`r", "`n")
}

function Get-SubsystemIdFromGeneratedContent {
    param([Parameter(Mandatory = $true)][string]$Content)

    foreach ($line in ($Content -split "`r?`n")) {
        if ($line.StartsWith($SubsystemIdMarkerPrefix)) {
            return $line.Substring($SubsystemIdMarkerPrefix.Length).Trim()
        }
    }

    return $null
}

function Get-CustomConstantsBySubsystemId {
    param([Parameter(Mandatory = $true)][string]$ConstantsDir)

    $customBlocks = @{}
    if (-not (Test-Path $ConstantsDir)) {
        return $customBlocks
    }

    Get-ChildItem -Path $ConstantsDir -Filter "*Constants.java" -File | ForEach-Object {
        $content = Get-Content -Path $_.FullName -Raw
        if (-not $content.Contains($GeneratedFileMarker)) {
            return
        }

        $id = Get-SubsystemIdFromGeneratedContent $content
        if (-not [string]::IsNullOrWhiteSpace($id)) {
            $customBlock = Get-PreservedCustomConstantsBlock $_.FullName
            if (-not [string]::IsNullOrWhiteSpace($customBlock)) {
                $customBlocks[$id] = $customBlock
            }
        }
    }

    return $customBlocks
}

function Set-CustomConstantsBlock {
    param(
        [Parameter(Mandatory = $true)][string]$Content,
        [AllowNull()][string]$CustomContent
    )

    if ([string]::IsNullOrWhiteSpace($CustomContent)) {
        return $Content
    }

    $start = $Content.IndexOf($CustomConstantsStartMarker) + $CustomConstantsStartMarker.Length
    $end = $Content.IndexOf($CustomConstantsEndMarker)
    if ($start -lt $CustomConstantsStartMarker.Length -or $end -lt 0) {
        return $Content
    }

    return $Content.Substring(0, $start) + "`n" + $CustomContent.Trim("`r", "`n") + "`n" + $Content.Substring($end)
}

function Write-ConstantsFile {
    param(
        [Parameter(Mandatory = $true)]$Subsystem,
        [Parameter(Mandatory = $true)]$Metadata,
        [Parameter(Mandatory = $true)]$CustomBlocksById
    )

    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    New-Item -ItemType Directory -Force -Path $constantsDir | Out-Null

    $outputFile = Join-Path $constantsDir "$($Metadata.PascalName)Constants.java"
    $customContent = if ($CustomBlocksById.ContainsKey($Metadata.Id)) {
        $CustomBlocksById[$Metadata.Id]
    } else {
        Get-PreservedCustomConstantsBlock $outputFile
    }
    $content = if ($Metadata.Type -eq "velocity") {
        New-VelocityConstantsContent $Subsystem $Metadata
    } else {
        New-PositionConstantsContent $Subsystem $Metadata
    }
    $content = Set-CustomConstantsBlock $content $customContent

    Set-Content -Path $outputFile -Value $content -Encoding ascii
    return $outputFile
}

function Remove-DeletedGeneratedFiles {
    param([Parameter(Mandatory = $true)]$Subsystems)

    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    if (-not (Test-Path $constantsDir)) {
        return
    }

    $wantedFiles = @{}
    foreach ($subsystem in @($Subsystems)) {
        $metadata = Get-SubsystemMetadata $subsystem
        $wantedFiles["$($metadata.PascalName)Constants.java"] = $true
    }

    Get-ChildItem -Path $constantsDir -Filter "*Constants.java" -File | ForEach-Object {
        $content = Get-Content -Path $_.FullName -Raw
        if ($content.Contains($GeneratedFileMarker) -and -not $wantedFiles.ContainsKey($_.Name)) {
            Remove-Item -LiteralPath $_.FullName -Force
            Write-Host "Deleted removed subsystem constants $($_.Name)"
        }
    }
}

function Update-SubsystemsFromJson {
    param([Parameter(Mandatory = $true)][string]$JsonPath)

    $document = Read-SubsystemDocument $JsonPath
    $subsystems = @($document.subsystems)

    $constantsBarrel = Join-Path (Get-Location) "src/main/java/frc/robot/Constants.java"
    if (-not (Test-Path $constantsBarrel)) {
        throw "Missing src/main/java/frc/robot/Constants.java. Run robotLibraryInstall first."
    }

    $stateMachineFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/StateMachine.java"
    if (-not (Test-Path $stateMachineFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/StateMachine.java. Run robotLibraryInstall first."
    }

    $written = @()
    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    $customBlocksById = Get-CustomConstantsBySubsystemId $constantsDir
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $written += Write-ConstantsFile $subsystem $metadata $customBlocksById
    }

    Rewrite-ConstantsBlock $constantsBarrel $subsystems
    Rewrite-StateMachineBlock $stateMachineFile $subsystems
    Remove-DeletedGeneratedFiles $subsystems
    Save-SubsystemDocument $JsonPath $document

    foreach ($file in $written) {
        Write-Host "Generated $file"
    }
    Write-Host "Updated Constants.java and StateMachine.java from $JsonPath"
}

function Invoke-BuildIfNeeded {
    if ($SkipBuild) {
        return
    }

    $isWindowsHost = [System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT
    $gradlew = if ($isWindowsHost) { ".\gradlew.bat" } else { "./gradlew" }
    if (Test-Path $gradlew) {
        & $gradlew --no-daemon --console=plain build
        if ($LASTEXITCODE -ne 0) {
            exit $LASTEXITCODE
        }
    } else {
        Write-Host "Skipped build because no Gradle wrapper was found."
    }
}

if ($UpdateSubsystems) {
    Update-SubsystemsFromJson $SubsystemsJson
    Invoke-BuildIfNeeded
    exit 0
}

