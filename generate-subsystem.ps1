function Get-BindingMethodNeedsValue {
    param(
        [Parameter(Mandatory = $true)]$Subsystem,
        [Parameter(Mandatory = $true)][string]$Method
    )

    $type = (Get-SubsystemMetadata $Subsystem).Type
    $valueMethods = switch ($type) {
        "absoluteposition" { @("setPositionRotations", "setPositionDegrees", "setVoltage") }
        "relativeposition" { @("setPosition", "setPositionRotations", "setVoltage") }
        default { @("setVelocity", "setVoltage") }
    }
    $voidMethods = switch ($type) {
        "absoluteposition" { @("stopPosition") }
        "relativeposition" { @("zeroEncoder") }
        default { @("stopVelocity", "brake") }
    }

    if ($valueMethods -contains $Method) {
        return $true
    }
    if ($voidMethods -contains $Method) {
        return $false
    }

    throw "Unsupported method '$Method' for subsystem '$($Subsystem.name)' of type '$type'."
}

function Convert-ToJavaIdentifier {
    param(
        [Parameter(Mandatory = $true)][string]$Value,
        [string]$Fallback = "bindingValue"
    )

    $parts = @(Get-JavaIdentifierParts $Value)
    if ($parts.Count -eq 0) {
        $parts = @(Get-JavaIdentifierParts $Fallback)
    }

    $identifier = ($parts | ForEach-Object {
        $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1).ToLowerInvariant()
    }) -join ""
    return Convert-ToCamelCase $identifier
}

function Convert-ToJavaConstantName {
    param([Parameter(Mandatory = $true)][string]$Value)

    $parts = @(Get-JavaIdentifierParts $Value)
    if ($parts.Count -eq 0) {
        throw "Binding constant name '$Value' is not a valid Java identifier."
    }

    return ($parts | ForEach-Object { $_.ToUpperInvariant() }) -join "_"
}

function Convert-ToJavaStringLiteral {
    param([AllowNull()][string]$Value)

    if ($null -eq $Value) {
        return '""'
    }

    return '"' + $Value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function Format-JavaDoubleLiteral {
    param([Parameter(Mandatory = $true)]$Value)

    $text = $Value.ToString()
    if ($text -notmatch '\.' -and $text -notmatch '[eE]') {
        $text = "$text.0"
    }

    return $text
}

