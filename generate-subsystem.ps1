function Read-SubsystemDocument {
    param([Parameter(Mandatory = $true)][string]$Path)

    if (-not (Test-Path $Path)) {
        return [pscustomobject]@{ subsystems = @() }
    }

    $document = Get-Content -Path $Path -Raw | ConvertFrom-Json
    if (-not ($document.PSObject.Properties.Name -contains "subsystems")) {
        $document | Add-Member -MemberType NoteProperty -Name subsystems -Value @()
    }

    $document.subsystems = @($document.subsystems)
    foreach ($subsystem in @($document.subsystems)) {
        if (-not ($subsystem.PSObject.Properties.Name -contains "id") -or [string]::IsNullOrWhiteSpace($subsystem.id)) {
            $subsystem | Add-Member -MemberType NoteProperty -Name id -Value (Get-StableSubsystemId $subsystem) -Force
        }
        if (-not ($subsystem.PSObject.Properties.Name -contains "focEnabled")) {
            $subsystem | Add-Member -MemberType NoteProperty -Name focEnabled -Value $true -Force
        }
        if ($subsystem.type.ToString().ToLowerInvariant() -eq "velocitytorque" -and -not ($subsystem.PSObject.Properties.Name -contains "torqueFF")) {
            $subsystem | Add-Member -MemberType NoteProperty -Name torqueFF -Value "0.0" -Force
        }
    }
    return $document
}

function Save-SubsystemDocument {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)]$Document
    )

    $Document.subsystems = @($Document.subsystems | Sort-Object { (Get-SubsystemMetadata $_).PascalName })
    $Document | ConvertTo-Json -Depth 12 | Set-Content -Path $Path -Encoding ascii
}

function Read-BindingDocument {
    param([Parameter(Mandatory = $true)][string]$Path)

    if (-not (Test-Path $Path)) {
        return [pscustomobject]@{ bindings = @() }
    }

    $document = Get-Content -Path $Path -Raw | ConvertFrom-Json
    if (-not ($document.PSObject.Properties.Name -contains "bindings")) {
        $document | Add-Member -MemberType NoteProperty -Name bindings -Value @()
    }

    $document.bindings = @($document.bindings)
    return $document
}

function Save-BindingDocument {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)]$Document
    )

    $Document.bindings = @($Document.bindings | Sort-Object { $_.name })
    $Document | ConvertTo-Json -Depth 12 | Set-Content -Path $Path -Encoding ascii
}

function Get-JsonPropertyValue {
    param(
        [Parameter(Mandatory = $true)]$Object,
        [Parameter(Mandatory = $true)][string]$Name,
        $DefaultValue = $null
    )

    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property -or $null -eq $property.Value) {
        return $DefaultValue
    }

    return $property.Value
}

function Upsert-SubsystemDocumentEntry {
    param(
        [Parameter(Mandatory = $true)]$Document,
        [Parameter(Mandatory = $true)]$Subsystem
