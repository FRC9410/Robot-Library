function Prompt-Value {
    param(
        [Parameter(Mandatory = $true)][string]$Message,
        [string]$DefaultValue = $null
    )

    $suffix = ""
    if ($null -ne $DefaultValue -and $DefaultValue.Length -gt 0) {
        $suffix = " [$DefaultValue]"
    }

    [Console]::WriteLine()
    [Console]::Write("POWERLIB> $Message$suffix`: ")
    $value = [Console]::ReadLine()
    if ([string]::IsNullOrWhiteSpace($value)) {
        return $DefaultValue
    }

    return $value.Trim()
}

function Prompt-Required {
    param([Parameter(Mandatory = $true)][string]$Message)

    do {
        $value = Prompt-Value $Message
    } while ([string]::IsNullOrWhiteSpace($value))

    return $value.Trim()
}

function Prompt-Enum {
    param(
        [Parameter(Mandatory = $true)][string]$Message,
        [Parameter(Mandatory = $true)][string[]]$AcceptedValues,
        [Parameter(Mandatory = $true)][string]$DefaultValue
    )

    $acceptedText = $AcceptedValues -join ", "
    while ($true) {
        $value = Prompt-Value "$Message (accepted: $acceptedText)" $DefaultValue
        foreach ($accepted in $AcceptedValues) {
            if ($value -ieq $accepted) {
                return $accepted
            }
        }

        Write-Host "Accepted values: $acceptedText"
    }
}

function Prompt-Boolean {
    param(
        [Parameter(Mandatory = $true)][string]$Message,
        [bool]$DefaultValue = $false
    )

    $defaultText = if ($DefaultValue) { "y" } else { "n" }
    while ($true) {
        $value = (Prompt-Value "$Message (accepted: y, n)" $defaultText).ToLowerInvariant()
        if ($value -eq "y" -or $value -eq "yes" -or $value -eq "true") {
            return $true
        }
        if ($value -eq "n" -or $value -eq "no" -or $value -eq "false") {
            return $false
        }

        Write-Host "Accepted values: y, n"
    }
}

function Prompt-Int {
    param(
        [Parameter(Mandatory = $true)][string]$Message,
        [Nullable[int]]$DefaultValue = $null
    )

    while ($true) {
        $defaultText = if ($null -eq $DefaultValue) { $null } else { $DefaultValue.ToString() }
        $value = Prompt-Value $Message $defaultText
        $parsed = 0
        if ([int]::TryParse($value, [ref]$parsed)) {
            return $parsed
        }

        Write-Host "Please enter a whole number."
    }
}

function Prompt-DoubleText {
    param(
        [Parameter(Mandatory = $true)][string]$Message,
        [string]$DefaultValue = $null
    )

    while ($true) {
        $value = Prompt-Value $Message $DefaultValue
        $parsed = 0.0
        if ([double]::TryParse($value, [System.Globalization.NumberStyles]::Float, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$parsed)) {
            return $value
        }

        Write-Host "Please enter a number."
    }
}

function Prompt-OptionalDoubleText {
    param([Parameter(Mandatory = $true)][string]$Label)

    $value = Prompt-Value "$Label (blank for Optional.empty)" ""
    if ([string]::IsNullOrWhiteSpace($value)) {
        return $null
    }

    $parsed = 0.0
    if (-not [double]::TryParse($value, [System.Globalization.NumberStyles]::Float, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$parsed)) {
        throw "Please enter a number for $Label."
    }

    return $value
}

function Get-JavaIdentifierParts {
    param([Parameter(Mandatory = $true)][string]$Value)

    $splitWords = [regex]::Replace($Value, "([a-z])([A-Z])", '$1 $2')
    return @($splitWords -split "[^A-Za-z0-9]+" | Where-Object { $_.Length -gt 0 })
}

function Convert-ToPascalCase {
    param([Parameter(Mandatory = $true)][string]$Value)

    $parts = @(Get-JavaIdentifierParts $Value)
    if ($parts.Count -eq 0) {
        throw "Subsystem name must contain at least one letter or number."
    }

    return ($parts | ForEach-Object {
        $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1)
    }) -join ""
}

function Convert-ToCamelCase {
    param([Parameter(Mandatory = $true)][string]$Pascal)
    return $Pascal.Substring(0, 1).ToLowerInvariant() + $Pascal.Substring(1)
}

function Convert-ToConstantPrefix {
    param([Parameter(Mandatory = $true)][string]$RawName)
    return (@(Get-JavaIdentifierParts $RawName) | ForEach-Object { $_.ToUpperInvariant() }) -join "_"
}

function Get-StableSubsystemId {
    param([Parameter(Mandatory = $true)]$Subsystem)

    if (($Subsystem.PSObject.Properties.Name -contains "id") -and -not [string]::IsNullOrWhiteSpace($Subsystem.id)) {
        return $Subsystem.id.ToString()
    }

    return Convert-ToCamelCase (Convert-ToPascalCase $Subsystem.name)
}

function Get-SubsystemMetadata {
    param([Parameter(Mandatory = $true)]$Subsystem)

    $pascal = Convert-ToPascalCase $Subsystem.name
    $type = $Subsystem.type.ToString().ToLowerInvariant()
    if ($type -ne "velocity" -and $type -ne "position") {
        throw "Unsupported subsystem type '$($Subsystem.type)' for '$($Subsystem.name)'. Accepted values: velocity, position."
    }

    return [pscustomobject]@{
        Id = Get-StableSubsystemId $Subsystem
        Name = $Subsystem.name
        Type = $type
        PascalName = $pascal
        CamelName = Convert-ToCamelCase $pascal
        ConstantPrefix = Convert-ToConstantPrefix $Subsystem.name
        SubsystemClassName = if ($type -eq "velocity") { "VelocitySubsystem" } else { "PositionSubsystem" }
        ConfigConstantName = "$(Convert-ToConstantPrefix $Subsystem.name)_CONFIG"
    }
}

function Get-NeutralModeExpression {
    param([Parameter(Mandatory = $true)][string]$Value)

    if ($Value -ieq "Coast") {
        return "NeutralModeValue.Coast"
    }
    if ($Value -ieq "Brake") {
        return "NeutralModeValue.Brake"
    }

    throw "Unsupported neutral mode '$Value'. Accepted values: Brake, Coast."
}

function Get-OptionalDoubleExpression {
    param($Value)

    if ($null -eq $Value -or [string]::IsNullOrWhiteSpace($Value.ToString())) {
        return "Optional.empty()"
    }

    return "Optional.of($Value)"
}

function Format-IndentedList {
    param(
        [Parameter(Mandatory = $true)][string[]]$Expressions,
        [Parameter(Mandatory = $true)][string]$Indent
    )

    return ($Expressions | ForEach-Object { "$Indent$_" }) -join ",`n"
}

function Convert-MotorsToExpressions {
    param([Parameter(Mandatory = $true)]$Subsystem)

    $motors = @($Subsystem.motors)
    if ($motors.Count -eq 0) {
        throw "Subsystem '$($Subsystem.name)' must have at least one motor."
    }

    $leader = $motors | Where-Object { $_.role -eq "leader" } | Select-Object -First 1
    if ($null -eq $leader) {
        throw "Subsystem '$($Subsystem.name)' must have one leader motor."
    }

    $lines = @("MotorConfig.leader($($leader.id), $(Get-NeutralModeExpression $leader.neutralMode), $($leader.reversed.ToString().ToLowerInvariant()))")
    foreach ($follower in ($motors | Where-Object { $_.role -eq "follower" })) {
        $lines += "MotorConfig.follower($($follower.id), $($follower.reversed.ToString().ToLowerInvariant()))"
    }

    return $lines
}

function New-InteractiveMotors {
    $leaderId = Prompt-Int "Leader motor CAN ID"
    $neutral = Prompt-Enum "Leader neutral mode" @("Brake", "Coast") "Brake"
    $leaderReversed = Prompt-Boolean "Leader reversed?" $false

    $motors = @(
        [pscustomobject]@{
            role = "leader"
            id = $leaderId
            neutralMode = $neutral
            reversed = $leaderReversed
        }
    )

    $followerIds = Prompt-Value "Follower motor CAN IDs, comma-separated (blank for none)" ""
    foreach ($idText in ($followerIds -split "," | ForEach-Object { $_.Trim() } | Where-Object { $_.Length -gt 0 })) {
        $followerId = [int]$idText
        $motors += [pscustomobject]@{
            role = "follower"
            id = $followerId
            reversed = Prompt-Boolean "Follower $followerId reversed?" $false
        }
    }

    return $motors
}

function New-InteractivePidConfig {
    if (-not (Prompt-Boolean "Configure PID/feedforward values?" $false)) {
        return [ordered]@{
            kP = "0.0"
            kI = "0.0"
            kD = "0.0"
            kG = "0.0"
            kS = $null
            kV = $null
            kA = $null
        }
    }

    return [ordered]@{
        kP = Prompt-DoubleText "kP" "0.0"
        kI = Prompt-DoubleText "kI" "0.0"
        kD = Prompt-DoubleText "kD" "0.0"
        kG = Prompt-DoubleText "kG" "0.0"
        kS = Prompt-OptionalDoubleText "kS"
        kV = Prompt-OptionalDoubleText "kV"
        kA = Prompt-OptionalDoubleText "kA"
    }
}

function New-InteractiveSubsystem {
    $rawName = Prompt-Required "Subsystem name, example shooter"
    $type = (Prompt-Enum "Subsystem type" @("velocity", "position") "velocity").ToLowerInvariant()
    $stableId = Convert-ToCamelCase (Convert-ToPascalCase $rawName)

    $subsystem = [ordered]@{
        id = $stableId
        name = $rawName
        type = $type
        motors = @(New-InteractiveMotors)
        pid = New-InteractivePidConfig
        ratios = [ordered]@{
            sensorToMechanism = Prompt-DoubleText "Sensor-to-mechanism ratio" "1.0"
            rotorToSensor = Prompt-DoubleText "Rotor-to-sensor ratio" "1.0"
        }
        motionMagic = [ordered]@{}
    }

    if ($type -eq "position") {
        $subsystem.cancoder = [ordered]@{
            id = Prompt-Int "CANcoder CAN ID"
            magnetOffset = Prompt-DoubleText "CANcoder magnet offset rotations" "0.0"
            discontinuityPoint = Prompt-DoubleText "CANcoder discontinuity point rotations" "0.5"
        }
        $subsystem.motionMagic.cruiseVelocity = Prompt-DoubleText "Motion Magic cruise velocity" "0.0"
        $subsystem.motionMagic.acceleration = Prompt-DoubleText "Motion Magic acceleration" "0.0"
        $subsystem.position = [ordered]@{
            units = Prompt-Value "Position units" "rotations"
            default = Prompt-OptionalDoubleText "Default position"
        }
    } else {
        $subsystem.motionMagic.acceleration = Prompt-DoubleText "Motion Magic acceleration" "0.0"
    }

    return [pscustomobject]$subsystem
}

function Read-SubsystemDocument {
    param([Parameter(Mandatory = $true)][string]$Path)

    if (-not (Test-Path $Path)) {
        return [pscustomobject]@{ subsystems = @() }
    }

    $document = Get-Content -Path $Path -Raw | ConvertFrom-Json
    if (-not ($document.PSObject.Properties.Name -contains "subsystems")) {
        $document | Add-Member -MemberType NoteProperty -Name subsystems -Value @()
    }

    $document.subsystems = @($document.subsystems)
    foreach ($subsystem in @($document.subsystems)) {
        if (-not ($subsystem.PSObject.Properties.Name -contains "id") -or [string]::IsNullOrWhiteSpace($subsystem.id)) {
            $subsystem | Add-Member -MemberType NoteProperty -Name id -Value (Get-StableSubsystemId $subsystem) -Force
        }
    }
    return $document
}

function Save-SubsystemDocument {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)]$Document
    )

    $Document.subsystems = @($Document.subsystems | Sort-Object { (Get-SubsystemMetadata $_).PascalName })
    $Document | ConvertTo-Json -Depth 12 | Set-Content -Path $Path -Encoding ascii
}

function Upsert-SubsystemDocumentEntry {
    param(
        [Parameter(Mandatory = $true)]$Document,
        [Parameter(Mandatory = $true)]$Subsystem
    )

    $metadata = Get-SubsystemMetadata $Subsystem
    $Document.subsystems = @($Document.subsystems | Where-Object { (Get-SubsystemMetadata $_).Id -ne $metadata.Id })
    $Document.subsystems += $Subsystem
}

