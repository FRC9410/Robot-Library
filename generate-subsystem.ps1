    $subsystem = New-InteractiveSubsystem
    Upsert-SubsystemDocumentEntry $document $subsystem
    Save-SubsystemDocument $SubsystemsJson $document
    Update-SubsystemsFromJson $SubsystemsJson
    $addAnother = Prompt-Boolean "Add another subsystem?" $false
} while ($addAnother)

Invoke-BuildIfNeeded
