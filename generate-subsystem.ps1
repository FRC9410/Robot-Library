    $metadata = Get-SubsystemMetadata $subsystem
    $constantProperty = Get-JsonPropertyValue $Command "constantName"
    if ([string]::IsNullOrWhiteSpace($constantProperty)) {
        throw "$Description needs a constant name."
    }
    $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
    return "Constants.$($metadata.PascalName).$constantName"
}

function New-InstantBindingCommandExpression {
    param(
        [Parameter(Mandatory = $true)]$Command,
        [Parameter(Mandatory = $true)]$Subsystems,
        [Parameter(Mandatory = $true)][string]$CommandOwner
    )

    $commandCall = New-InstantBindingCommandCall $Command $Subsystems $CommandOwner
    return "new InstantCommand(() -> { $($commandCall.Call) }, $($commandCall.Requirement))"
}

function New-RunBindingCommandExpression {
    param(
        [Parameter(Mandatory = $true)]$Command,
        [Parameter(Mandatory = $true)]$Subsystems,
        [Parameter(Mandatory = $true)][string]$CommandOwner
    )

    $commandCall = New-InstantBindingCommandCall $Command $Subsystems $CommandOwner
    return "Commands.run(() -> { $($commandCall.Call) }, $($commandCall.Requirement))"
}

function New-InstantBindingGroupExpression {
    param(
        [Parameter(Mandatory = $true)]$Commands,
        [Parameter(Mandatory = $true)]$Subsystems,
        [Parameter(Mandatory = $true)][string]$CommandOwner
    )

    $commandCalls = @($Commands | ForEach-Object { New-InstantBindingCommandCall $_ $Subsystems $CommandOwner })
    $requirements = @($commandCalls | ForEach-Object { $_.Requirement } | Select-Object -Unique)
    $calls = ($commandCalls | ForEach-Object { $_.Call }) -join " "
    return "new InstantCommand(() -> { $calls }, $($requirements -join ', '))"
}

function Test-BindingCommandGroupContainsKind {
    param(
        [Parameter(Mandatory = $true)]$Commands,
        [Parameter(Mandatory = $true)][string]$Kind
    )

    foreach ($command in @($Commands)) {
        $commandKind = Get-BindingCommandKind $command
        if ($commandKind -eq $Kind) {
            return $true
        }
        if ($commandKind -eq "sequence" -or $commandKind -eq "parallel" -or $commandKind -eq "parallelRace") {
            if (Test-BindingCommandGroupContainsKind (Get-JsonPropertyValue $command "children" @()) $Kind) {
                return $true
            }
        }
    }

    return $false
}

function New-BindingCommandExpression {
    param(
        [Parameter(Mandatory = $true)]$Command,
        [Parameter(Mandatory = $true)]$Subsystems,
        [Parameter(Mandatory = $true)][string]$CommandOwner
    )

    $kind = Get-BindingCommandKind $Command
    if ($kind -eq "function") {
        return New-InstantBindingCommandExpression $Command $Subsystems $CommandOwner
    }
    if ($kind -eq "wait") {
        $fallback = Get-BindingConstantReference $Command $Subsystems 'Wait command'
        $variableKey = Get-BindingCommandVariableKey $Command $Subsystems 'Wait command'
        return "Commands.waitSeconds(PowerRobotContainer.getCommandVariable($(Convert-ToJavaStringLiteral $CommandOwner), $(Convert-ToJavaStringLiteral $variableKey), $fallback))"
    }

    $children = @(Get-JsonPropertyValue $Command "children" @())
    if ($children.Count -eq 0) {
        throw "Binding command group '$kind' must contain at least one child command."
    }

    if ($kind -eq "sequence") {
        $childExpressions = @($children | ForEach-Object { New-BindingCommandExpression $_ $Subsystems $CommandOwner })
        return "new SequentialCommandGroup($($childExpressions -join ', '))"
    }
    if ($kind -eq "parallel") {
        $childExpressions = @($children | ForEach-Object { New-BindingCommandExpression $_ $Subsystems $CommandOwner })
        return "new ParallelCommandGroup($($childExpressions -join ', '))"
    }

    $raceContainsWait = Test-BindingCommandGroupContainsKind $children "wait"
    $childExpressions = @($children | ForEach-Object {
        if ($raceContainsWait -and (Get-BindingCommandKind $_) -eq "function") {
            New-RunBindingCommandExpression $_ $Subsystems $CommandOwner
        } else {
            New-BindingCommandExpression $_ $Subsystems $CommandOwner
        }
    })
    return "new ParallelRaceGroup($($childExpressions -join ', '))"
}

function Get-BindingCommandVariableDefaultLines {
    param(
        [Parameter(Mandatory = $true)]$Command,
        [Parameter(Mandatory = $true)]$Subsystems,
        [Parameter(Mandatory = $true)][string]$CommandOwner
    )

    $kind = Get-BindingCommandKind $Command
    if ($kind -eq "function") {
        $subsystemId = (Get-JsonPropertyValue $Command "subsystemId" "").ToString()
        $method = (Get-JsonPropertyValue $Command "method" "").ToString()
        $subsystem = Find-SubsystemById $Subsystems $subsystemId
        if (-not (Get-BindingMethodNeedsValue $subsystem $method)) {
            return @()
        }

        $metadata = Get-SubsystemMetadata $subsystem
        $constantProperty = Get-JsonPropertyValue $Command "constantName"
        if ([string]::IsNullOrWhiteSpace($constantProperty)) {
            throw "Binding command '$method' for subsystem '$($metadata.Name)' needs a constant name."
        }

        $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
        $variableKey = Get-BindingCommandVariableKey $Command $Subsystems "Binding command '$method'"
        return @("    PowerRobotContainer.setCommandVariableDefault($(Convert-ToJavaStringLiteral $CommandOwner), $(Convert-ToJavaStringLiteral $variableKey), Constants.$($metadata.PascalName).$constantName);")
    }

    if ($kind -eq "wait") {
        $fallback = Get-BindingConstantReference $Command $Subsystems 'Wait command'
        $variableKey = Get-BindingCommandVariableKey $Command $Subsystems 'Wait command'
        return @("    PowerRobotContainer.setCommandVariableDefault($(Convert-ToJavaStringLiteral $CommandOwner), $(Convert-ToJavaStringLiteral $variableKey), $fallback);")
    }

    $lines = @()
    foreach ($child in @(Get-JsonPropertyValue $Command "children" @())) {
        $lines += @(Get-BindingCommandVariableDefaultLines $child $Subsystems $CommandOwner)
    }

    return $lines
}

function Write-PowerButtonBindingsFile {
    param(
        [Parameter(Mandatory = $true)]$Bindings,
        [Parameter(Mandatory = $true)]$Subsystems
    )

    $outputFile = Join-Path (Get-Location) "src/main/java/frc/robot/PowerButtonBindings.java"
    $lines = @()
    $lines += "package frc.robot;"
    $lines += ""
    $lines += "$GeneratedFileMarker"
    $lines += ""
    $lines += "import edu.wpi.first.wpilibj2.command.Command;"
    $lines += "import edu.wpi.first.wpilibj2.command.Commands;"
    $lines += "import edu.wpi.first.wpilibj2.command.InstantCommand;"
    $lines += "import edu.wpi.first.wpilibj2.command.ParallelCommandGroup;"
    $lines += "import edu.wpi.first.wpilibj2.command.ParallelRaceGroup;"
    $lines += "import edu.wpi.first.wpilibj2.command.SequentialCommandGroup;"
    $lines += "import edu.wpi.first.wpilibj2.command.button.CommandXboxController;"
    $lines += "import frc.powerlib.PowerRobotContainer;"
    $lines += "import frc.robot.subsystems.StateMachine;"
    $lines += ""
    $lines += "public final class PowerButtonBindings {"
    $lines += "  private PowerButtonBindings() {}"
    $lines += ""
    $lines += "  public static void configure("
    $lines += "      CommandXboxController driverController,"
    $lines += "      CommandXboxController operatorController,"
    $lines += "      StateMachine stateMachine) {"

    $bindingIndex = 0
    foreach ($binding in @($Bindings)) {
        $commands = @(Get-JsonPropertyValue $binding "commands" @())
        if ($commands.Count -eq 0) {
            continue
        }

        $bindingName = (Get-JsonPropertyValue $binding "name" "binding").ToString()
        $bindingIdProperty = Get-JsonPropertyValue $binding "id"
        $bindingId = if (-not [string]::IsNullOrWhiteSpace($bindingIdProperty)) {
            $bindingIdProperty.ToString()
        } else {
            $bindingName
        }
        $commandOwner = Convert-ToJavaIdentifier $bindingId 'binding'
        $variableName = "$($commandOwner)Command$bindingIndex"
        $controller = (Get-JsonPropertyValue $binding "controller" "driver").ToString()
        $input = (Get-JsonPropertyValue $binding "input" "a").ToString()
        $event = (Get-JsonPropertyValue $binding "event" "onTrue").ToString()
        $triggerExpression = Get-BindingTriggerExpression $controller $input
        $eventName = Get-BindingEventName $event
        $commandVariableDefaults = @($commands | ForEach-Object { Get-BindingCommandVariableDefaultLines $_ $Subsystems $commandOwner } | Select-Object -Unique)
        $commandExpressions = @($commands | ForEach-Object { New-BindingCommandExpression $_ $Subsystems $commandOwner })
        $allInstantFunctions = @($commands | Where-Object { (Get-BindingCommandKind $_) -eq "function" }).Count -eq $commands.Count
        $commandExpression = if ($allInstantFunctions) {
            New-InstantBindingGroupExpression $commands $Subsystems $commandOwner
        } elseif ($commandExpressions.Count -eq 1) {
            $commandExpressions[0]
        } else {
            "new SequentialCommandGroup($($commandExpressions -join ', '))"
        }

        $lines += ""
        foreach ($defaultLine in $commandVariableDefaults) {
            $lines += $defaultLine
        }
        $lines += "    Command $variableName = $commandExpression;"
        $lines += "    $triggerExpression.$eventName($variableName);"
        $bindingIndex++
    }

    $lines += "  }"
    $lines += "}"

    Set-Content -Path $outputFile -Value ($lines -join "`n") -Encoding ascii
    return $outputFile
}

function Update-BindingsFromJson {
    param(
        [Parameter(Mandatory = $true)][string]$BindingJsonPath,
        [Parameter(Mandatory = $true)][string]$SubsystemJsonPath
    )

    $subsystemDocument = Read-SubsystemDocument $SubsystemJsonPath
    $bindingDocument = Read-BindingDocument $BindingJsonPath
    $subsystems = @($subsystemDocument.subsystems)
    $bindings = @($bindingDocument.bindings)

    $constantsBySubsystemId = @{}
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $constantsBySubsystemId[$metadata.Id] = @()
    }

    $collectConstants = {
        param($Command)

        $kind = Get-BindingCommandKind $Command
        if ($kind -ne "function") {
            if ($kind -eq "wait") {
                $subsystemId = (Get-JsonPropertyValue $Command "subsystemId" "").ToString()
                $subsystem = Find-SubsystemById $subsystems $subsystemId
                $constantProperty = Get-JsonPropertyValue $Command "constantName"
                if ([string]::IsNullOrWhiteSpace($constantProperty)) {
                    throw "Wait command needs a constant name."
                }
                $value = Get-JsonPropertyValue $Command "value"
                if ($null -eq $value) {
                    throw "Wait command needs a value."
                }

                $metadata = Get-SubsystemMetadata $subsystem
                $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
                $constantsBySubsystemId[$metadata.Id] += "  public static final double $constantName = $(Format-JavaDoubleLiteral $value);"
                return
            }
            foreach ($child in @(Get-JsonPropertyValue $Command "children" @())) {
                & $collectConstants $child
            }
            return
        }

        $subsystemId = (Get-JsonPropertyValue $Command "subsystemId" "").ToString()
        $method = (Get-JsonPropertyValue $Command "method" "").ToString()
        $subsystem = Find-SubsystemById $subsystems $subsystemId
        if (-not (Get-BindingMethodNeedsValue $subsystem $method)) {
            return
        }
        $constantProperty = Get-JsonPropertyValue $Command "constantName"
        if ([string]::IsNullOrWhiteSpace($constantProperty)) {
            throw "Binding command '$method' for subsystem '$($subsystem.name)' needs a constant name."
        }
        $value = Get-JsonPropertyValue $Command "value"
        if ($null -eq $value) {
            throw "Binding command '$method' for subsystem '$($subsystem.name)' needs a value."
        }

        $metadata = Get-SubsystemMetadata $subsystem
        $constantName = Convert-ToJavaConstantName $constantProperty.ToString()
        $constantsBySubsystemId[$metadata.Id] += "  public static final double $constantName = $(Format-JavaDoubleLiteral $value);"
    }

    foreach ($binding in $bindings) {
        foreach ($command in @(Get-JsonPropertyValue $binding "commands" @())) {
            & $collectConstants $command
        }
    }

    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $constantsFile = Join-Path $constantsDir "$($metadata.PascalName)Constants.java"
        if (-not (Test-Path $constantsFile)) {
            throw "Missing $constantsFile. Run subsystem update before binding update."
        }
        Rewrite-BindingConstantsBlock $constantsFile @($constantsBySubsystemId[$metadata.Id] | Select-Object -Unique)
    }

    $written = Write-PowerButtonBindingsFile $bindings $subsystems
    Save-BindingDocument $BindingJsonPath $bindingDocument
    Write-Host "Generated $written"
    Write-Host "Updated PowerButtonBindings.java and binding constants from $BindingJsonPath"
}

function Update-SubsystemsFromJson {
    param([Parameter(Mandatory = $true)][string]$JsonPath)

    $document = Read-SubsystemDocument $JsonPath
    $subsystems = @($document.subsystems)

    $constantsBarrel = Join-Path (Get-Location) "src/main/java/frc/robot/Constants.java"
    if (-not (Test-Path $constantsBarrel)) {
        throw "Missing src/main/java/frc/robot/Constants.java. Run robotLibraryInstall first."
    }

    $stateMachineFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/StateMachine.java"
    if (-not (Test-Path $stateMachineFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/StateMachine.java. Run robotLibraryInstall first."
    }

    $powerDashboardFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/PowerDashboard.java"
    if (-not (Test-Path $powerDashboardFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/PowerDashboard.java. Run robotLibraryInstall first."
    }

    $written = @()
    $characterizationWritten = @()
    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    $customBlocksById = Get-CustomConstantsBySubsystemId $constantsDir
    $written += Write-SwerveConstantsFile $document.swerve
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $written += Write-ConstantsFile $subsystem $metadata $customBlocksById
        $characterizationFile = Write-CharacterizationFile $subsystem $metadata
        if ($null -ne $characterizationFile) {
            $characterizationWritten += $characterizationFile
        }
    }

    Rewrite-ConstantsBlock $constantsBarrel $subsystems
    Rewrite-StateMachineBlock $stateMachineFile $subsystems
    Ensure-PowerDashboardRawNetworkTablesSupport $powerDashboardFile
    Rewrite-PowerDashboardCharacterizationBlock $powerDashboardFile $subsystems
    Remove-DeletedGeneratedFiles $subsystems
    Remove-StaleCharacterizationFiles $subsystems
    Save-SubsystemDocument $JsonPath $document

    foreach ($file in $written) {
        Write-Host "Generated $file"
    }
    foreach ($file in $characterizationWritten) {
        Write-Host "Generated $file"
    }
    Write-Host "Updated Constants.java, StateMachine.java, and PowerDashboard.java from $JsonPath"
}

function Invoke-BuildIfNeeded {
    if ($SkipBuild) {
        return
    }

    $isWindowsHost = [System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT
    $gradlew = if ($isWindowsHost) { ".\gradlew.bat" } else { "./gradlew" }
    if (Test-Path $gradlew) {
        & $gradlew --no-daemon --console=plain build
        if ($LASTEXITCODE -ne 0) {
            exit $LASTEXITCODE
        }
    } else {
        Write-Host "Skipped build because no Gradle wrapper was found."
    }
}

if ($UpdateSubsystems -or $UpdateBindings) {
    if ($UpdateSubsystems) {
        Update-SubsystemsFromJson $SubsystemsJson
    }
    if ($UpdateBindings) {
        Update-BindingsFromJson $BindingsJson $SubsystemsJson
    }
    Invoke-BuildIfNeeded
    exit 0
}

