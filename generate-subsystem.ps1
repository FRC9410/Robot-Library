function Move-ControllerPortToOI {
    param([Parameter(Mandatory = $true)]$Configuration)

    $directory = Join-Path (Get-Location) 'src/main/java/frc/robot/constants'
    $oldPath = Join-Path $directory 'RobotContainerConstants.java'
    $oiPath = Join-Path $directory 'OIConstants.java'
    $oldSource = if (Test-Path $oldPath) { Get-Content -LiteralPath $oldPath -Raw -Encoding UTF8 } else { '' }
    $original = Get-JavaConstantRows $oldSource | Where-Object { -not $_.custom -and $_.name -ceq 'DRIVER_CONTROLLER_PORT' } | Select-Object -First 1
    $oldEntry = $Configuration.files.PSObject.Properties['robot:RobotContainer']
    $port = if ($null -ne $oldEntry) { $oldEntry.Value.constants | Where-Object { -not $_.custom -and $_.name -ceq 'DRIVER_CONTROLLER_PORT' } | Select-Object -First 1 } else { $null }
    if ($null -eq $port) { $port = $original }
    if ($null -ne $port) {
        if (-not (Test-Path $oiPath)) { throw 'Missing OIConstants.java for controller port migration.' }
        $oiSource = Get-Content -LiteralPath $oiPath -Raw -Encoding UTF8
        $existingPort = Get-JavaConstantRows $oiSource | Where-Object { $_.name -ceq 'DRIVER_CONTROLLER_PORT' } | Select-Object -First 1
        if ($null -eq $existingPort) {
            $pattern = '(public\s+class\s+OIConstants\s*\{)'
            if (-not [regex]::IsMatch($oiSource, $pattern)) { throw 'Could not find OIConstants class for controller port migration.' }
            $oiSource = [regex]::Replace($oiSource, $pattern, ('$1' + "`n  public static final int DRIVER_CONTROLLER_PORT = $($port.value);`n"))
            [System.IO.File]::WriteAllText($oiPath, $oiSource, [System.Text.UTF8Encoding]::new($false))
        }
        if ($null -ne $original) {
            $oldSource = $oldSource.Remove($original.start, $original.end - $original.start)
            [System.IO.File]::WriteAllText($oldPath, $oldSource, [System.Text.UTF8Encoding]::new($false))
        }
        if ($null -ne $oldEntry) {
            $oldEntry.Value.constants = @($oldEntry.Value.constants | Where-Object { $_.custom -or $_.name -cne 'DRIVER_CONTROLLER_PORT' })
        }
        $oiEntry = $Configuration.files.PSObject.Properties['robot:OI']
        if ($null -eq $oiEntry) {
            $Configuration.files | Add-Member -MemberType NoteProperty -Name 'robot:OI' -Value ([pscustomobject]@{ constants = @() })
            $oiEntry = $Configuration.files.PSObject.Properties['robot:OI']
        }
        $oiEntry.Value.constants = @($oiEntry.Value.constants | Where-Object { $_.name -cne 'DRIVER_CONTROLLER_PORT' }) + @(
            [pscustomobject]@{ name = 'DRIVER_CONTROLLER_PORT'; type = 'int'; value = $port.value; custom = $false; tunable = $true }
        )
    }
    $containerPath = Join-Path (Get-Location) 'src/main/java/frc/robot/RobotContainer.java'
    if (Test-Path $containerPath) {
        $source = Get-Content -LiteralPath $containerPath -Raw -Encoding UTF8
        $updated = $source.Replace('Constants.RobotContainer.DRIVER_CONTROLLER_PORT', 'Constants.OI.DRIVER_CONTROLLER_PORT')
        if ($updated -cne $source) {
            [System.IO.File]::WriteAllText($containerPath, $updated, [System.Text.UTF8Encoding]::new($false))
        }
    }
}

function Format-ConfiguredConstant {
    param([Parameter(Mandatory = $true)]$Constant)
    if ($Constant.name -cnotmatch '^[A-Za-z_$][\w$]*$' -or [string]::IsNullOrWhiteSpace($Constant.value) -or $Constant.type -cnotmatch '^[A-Za-z_$][\w.$]*(\s*<\s*[\w.$?,<>\s]+>)?(\s*\[\])*\s*$') { throw 'Invalid constant in powerlib-constants.json.' }
    $numeric = Test-NumericConstantType $Constant.type
    $annotation = if ($numeric) { "@frc.powerlib.tuning.TunableConstant`n  " } else { '' }
    $modifier = if ($numeric) { 'volatile' } else { 'final' }
    return "${annotation}public static $modifier $($Constant.type) $($Constant.name) = $($Constant.value);"
}

function Write-ConfiguredConstants {
    param([Parameter(Mandatory = $true)]$Configuration, [Parameter(Mandatory = $true)][AllowEmptyCollection()]$Subsystems)
    $directory = Join-Path (Get-Location) 'src/main/java/frc/robot/constants'
    foreach ($target in @(Get-ConstantsConfigurationTargets $Subsystems)) {
        if ($null -eq $Configuration.files.PSObject.Properties[$target.key]) { continue }
        $path = Join-Path $directory "$($target.name)Constants.java"
        if (-not (Test-Path $path)) { continue }
        $source = Get-Content -LiteralPath $path -Raw -Encoding UTF8
        $constants = @($Configuration.files.PSObject.Properties[$target.key].Value.constants)
        $parsed = @(Get-JavaConstantRows $source)
        foreach ($original in @($parsed | Sort-Object start -Descending)) {
            if ($original.custom -or $target.customOnly -or $target.name -eq 'Swerve') { continue }
            $constant = $constants | Where-Object { -not $_.custom -and $_.name -ceq $original.name } | Select-Object -First 1
            if ($null -eq $constant) { continue }
            if ($constant.type -cne $original.type) { throw "Saved type of $($constant.name) does not match robot code." }
            $source = $source.Substring(0, $original.start) + (Format-ConfiguredConstant $constant) + $source.Substring($original.end)
        }
        $customContent = @($constants | Where-Object { $_.custom } | ForEach-Object { '  ' + (Format-ConfiguredConstant $_) }) -join "`n"
        $start = $source.IndexOf($CustomConstantsStartMarker)
        $end = $source.IndexOf($CustomConstantsEndMarker)
        if ($start -lt 0 -and $end -lt 0) {
            $closing = $source.LastIndexOf('}')
            $source = $source.Substring(0, $closing) + "$CustomConstantsStartMarker`n$CustomConstantsEndMarker`n" + $source.Substring($closing)
            $start = $source.IndexOf($CustomConstantsStartMarker)
            $end = $source.IndexOf($CustomConstantsEndMarker)
        }
        if ($start -lt 0 -or $end -le $start) { throw "Invalid custom constants markers in $path." }
        $start += $CustomConstantsStartMarker.Length
        $source = $source.Substring(0, $start) + "`n$customContent`n" + $source.Substring($end)
        [System.IO.File]::WriteAllText($path, $source + "`n", [System.Text.UTF8Encoding]::new($false))
    }
    [System.IO.File]::WriteAllText((Join-Path (Get-Location) 'power-tool/generated/powerlib-constants.json'), ($Configuration | ConvertTo-Json -Depth 16) + "`n", [System.Text.UTF8Encoding]::new($false))
}
function Ensure-SwerveCachedTuningSupport {
    param([Parameter(Mandatory = $true)][string]$SwervePath)

    if (-not (Test-Path -LiteralPath $SwervePath)) { return }
    $content = Get-Content -LiteralPath $SwervePath -Raw -Encoding UTF8
    $pattern = '(?m)^  private void applyTunableValues\(\) \{'
    # Custom drivetrains without the PowerLib tuning methods are managed by their owner.
    if (-not [regex]::IsMatch($content, $pattern)) { return }
    $syncCall = 'frc.powerlib.utils.DriveUtil.syncTunableValues();'
    if (-not $content.Contains($syncCall)) {
        $guard = @"
    if (!PowerRobotContainer.isTuningEnabled()) {
      return;
    }
    $syncCall
"@
        $content = [regex]::Replace($content, $pattern, ('$0' + "`n" + $guard))
    }
    $pattern = '(?m)(^  private double getSwerveVariable\(String key, double defaultValue\) \{\r?\n)    if \(!PowerRobotContainer\.isTuningEnabled\(\)\) \{\r?\n      return defaultValue;\r?\n    \}\r?\n\r?\n'
    $content = [regex]::Replace($content, $pattern, '$1')
    [System.IO.File]::WriteAllText($SwervePath, $content, [System.Text.UTF8Encoding]::new($false))
}

function Ensure-SubsystemTelemetrySupport {
    param([Parameter(Mandatory = $true)][string]$PowerDashboardPath)

    $content = Get-Content -Path $PowerDashboardPath -Raw
    $content = [regex]::Replace($content,
        '(?ms)^  private void publishSubsystemData\(\) \{.*?^  \}',
        "  private void publishSubsystemData() {`n    frc.powerlib.dashboard.SubsystemTelemetry.publish();`n  }")
    $content = [regex]::Replace($content,
        '(?ms)^  private void publishValue\(NetworkTable table, String key, Object value\) \{.*?^  \}\r?\n\r?\n', '')

    if (-not $content.Contains('private final frc.powerlib.dashboard.DriveTelemetry driveTelemetry;')) {
        $content = $content.Replace('  private final StateMachine stateMachine;',
            "  private final StateMachine stateMachine;`n  private final frc.powerlib.dashboard.DriveTelemetry driveTelemetry;")
        $driveInitialization = @'
    this.stateMachine = stateMachine;
    driveTelemetry = new frc.powerlib.dashboard.DriveTelemetry()
        .withPose(() -> stateMachine.drivetrain.getState().Pose)
        .withSpeeds(() -> stateMachine.drivetrain.getState().Speeds)
        .withState(() -> stateMachine.getWantedState().name());
'@
        $content = $content.Replace('    this.stateMachine = stateMachine;', $driveInitialization)
    }
    if (-not $content.Contains('driveTelemetry.publish();')) {
        $content = $content.Replace('  public void periodic() {',
            "  public void periodic() {`n    driveTelemetry.publish();")
    }
    Set-Content -Path $PowerDashboardPath -Value $content -Encoding ascii
}

function Ensure-TunableConstantsSupport {
    param([Parameter(Mandatory = $true)][string]$PowerDashboardPath)

    $content = Get-Content -Path $PowerDashboardPath -Raw -Encoding UTF8
    $registerCall = "frc.robot.constants.GeneratedTunableConstants.register();"
    $syncCall = "frc.powerlib.tuning.TunableConstants.sync();"
    if (-not $content.Contains($registerCall)) {
        $pattern = '(public\s+PowerDashboard\s*\(\s*StateMachine\s+\w+\s*\)\s*\{)'
        if (-not [regex]::IsMatch($content, $pattern)) { throw "Could not find PowerDashboard constructor for tunable constants registration." }
        $content = [regex]::Replace($content, $pattern, ('$1' + "`n    $registerCall"))
    }
    if (-not $content.Contains($syncCall)) {
        $pattern = 'syncSubsystemVariables\(\);'
        if (-not [regex]::IsMatch($content, $pattern)) { throw "Could not find PowerDashboard subsystem variable synchronization." }
        $content = [regex]::Replace($content, $pattern, ("syncSubsystemVariables();`n    $syncCall"))
    }
    foreach ($scope in @('Subsystem', 'Command')) {
        $field = "synced${scope}VariablesRevision"
        if (-not $content.Contains("private long $field")) {
            $pattern = '(?m)^  private double nextTuningModeSyncTime = 0\.0;'
            if (-not [regex]::IsMatch($content, $pattern)) { throw "Could not find PowerDashboard tuning state." }
            $content = [regex]::Replace($content, $pattern, ('$0' + "`n  private long $field = -1;"))
        }
        if ($content.Contains("revision == $field")) { continue }
        $ownerTable = if ($scope -eq 'Subsystem') { 'subsystemsTable' } else { 'commandsTable' }
        $method = @"
  private void sync${scope}Variables() {
    long revision = PowerRobotContainer.get${scope}VariablesRevision();
    if (!PowerRobotContainer.isTuningEnabled() && revision == $field) {
      return;
    }
    syncVariables(
        PowerRobotContainer.getAll${scope}Variables(),
        $ownerTable,
        PowerRobotContainer::update${scope}Variable);
    $field = revision;
  }
"@
        $pattern = '(?ms)^  private void sync' + $scope + 'Variables\(\) \{.*?^  \}'
        if (-not [regex]::IsMatch($content, $pattern)) { throw "Could not find PowerDashboard $scope variable synchronization." }
        $content = [regex]::Replace($content, $pattern, $method)
    }
    [System.IO.File]::WriteAllText($PowerDashboardPath, $content, [System.Text.UTF8Encoding]::new($false))
}

function Update-SubsystemsFromJson {
    param([Parameter(Mandatory = $true)][string]$JsonPath)

    $document = Read-SubsystemDocument $JsonPath
    $subsystems = @($document.subsystems)

    $constantsBarrel = Join-Path (Get-Location) "src/main/java/frc/robot/Constants.java"
    if (-not (Test-Path $constantsBarrel)) {
        throw "Missing src/main/java/frc/robot/Constants.java. Run robotLibraryInstall first."
    }

    $stateMachineFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/StateMachine.java"
    if (-not (Test-Path $stateMachineFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/StateMachine.java. Run robotLibraryInstall first."
    }

    $powerDashboardFile = Join-Path (Get-Location) "src/main/java/frc/robot/subsystems/PowerDashboard.java"
    if (-not (Test-Path $powerDashboardFile)) {
        throw "Missing src/main/java/frc/robot/subsystems/PowerDashboard.java. Run robotLibraryInstall first."
    }

    $written = @()
    $characterizationWritten = @()
    $constantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants"
    $customBlocksById = Get-CustomConstantsBySubsystemId $constantsDir
    $constantsConfiguration = Read-ConstantsConfiguration
    Import-ConstantsConfiguration $constantsConfiguration $subsystems $customBlocksById
    Move-ControllerPortToOI $constantsConfiguration
    $written += Write-SwerveConstantsFile $document.swerve
    foreach ($subsystem in $subsystems) {
        $metadata = Get-SubsystemMetadata $subsystem
        $written += Write-ConstantsFile $subsystem $metadata $customBlocksById
        $characterizationFile = Write-CharacterizationFile $subsystem $metadata
        if ($null -ne $characterizationFile) {
            $characterizationWritten += $characterizationFile
        }
    }

    Rewrite-ConstantsBlock $constantsBarrel $subsystems
    Rewrite-StateMachineBlock $stateMachineFile $subsystems
    Ensure-PowerDashboardRawNetworkTablesSupport $powerDashboardFile
    Ensure-SubsystemTelemetrySupport $powerDashboardFile
    Write-ConfiguredConstants $constantsConfiguration $subsystems
    Write-TunableConstantsRegistry $subsystems
    Ensure-TunableConstantsSupport $powerDashboardFile
    Ensure-SwerveCachedTuningSupport (Join-Path (Get-Location) 'src/main/java/frc/robot/subsystems/Swerve.java')
    Rewrite-PowerDashboardCharacterizationBlock $powerDashboardFile $subsystems
    Remove-DeletedGeneratedFiles $subsystems
    Remove-StaleCharacterizationFiles $subsystems
    Save-SubsystemDocument $JsonPath $document

    foreach ($file in $written) {
        Write-Host "Generated $file"
    }
    foreach ($file in $characterizationWritten) {
        Write-Host "Generated $file"
    }
    Write-Host "Updated Constants.java, StateMachine.java, and PowerDashboard.java from $JsonPath"
}

function Invoke-BuildIfNeeded {
    if ($SkipBuild) {
        return
    }

    $isWindowsHost = [System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT
    $gradlew = if ($isWindowsHost) { ".\gradlew.bat" } else { "./gradlew" }
    if (Test-Path $gradlew) {
        & $gradlew --no-daemon --console=plain build
        if ($LASTEXITCODE -ne 0) {
            exit $LASTEXITCODE
        }
    } else {
        Write-Host "Skipped build because no Gradle wrapper was found."
    }
}

