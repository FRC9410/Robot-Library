import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { configFixture } from "./config-fixture.mjs";
const {api, root, file} = await configFixture("localization-config");
const source = file("constants/VisionConstants.java");
let initial = await api.readLocalizationConfig(root);
const config = {...initial.config,position:{targetAreaThreshold:1,maxTargetDistanceMeters:5},heading:{maxTagDistanceMeters:5,singleTagMaxDistanceMeters:3}};
await api.saveLocalizationConfig(root,config);
let saved = await api.readLocalizationConfig(root);
assert.deepEqual(saved.config.position,config.position);
assert.deepEqual(saved.config.heading,config.heading);
const before=await fs.readFile(source,"utf8");
await api.saveLocalizationConfig(root,saved.config);
assert.equal(await fs.readFile(source,"utf8"),before,"No-op save preserves byte-for-byte source");
for(const patch of [{heading:{maxTagDistanceMeters:0,singleTagMaxDistanceMeters:1}},{position:{targetAreaThreshold:-1,maxTargetDistanceMeters:5}}]) await assert.rejects(api.saveLocalizationConfig(root,{...saved.config,...patch}));
await assert.rejects(api.saveLocalizationConfig(root,config),/changed since/);
// Active fluent arguments take priority over unused scalar declarations.
await fs.writeFile(source,before.replace(/\.withDistanceLimits\(\s*HEADING_MAX_TAG_DISTANCE_METERS,\s*HEADING_SINGLE_TAG_MAX_DISTANCE_METERS\)/,".withDistanceLimits(6.0, 2.5)"));
saved=await api.readLocalizationConfig(root);
assert.equal(saved.config.heading.maxTagDistanceMeters,6);
saved.config.heading.maxTagDistanceMeters=7;
await api.saveLocalizationConfig(root,saved.config);
assert.equal((await api.readLocalizationConfig(root)).config.heading.maxTagDistanceMeters,7);
assert.equal((await fs.readFile(source,"utf8")).match(/withDistanceLimits/g).length,1);
console.log("Localization source checks passed: live policy bindings, validation, stale revisions, no-op saves and no duplicated fluent policy.");
