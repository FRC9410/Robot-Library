function Write-SubsystemSimConstantsFiles {
    param(
        [Parameter(Mandatory = $true)][string]$SimConfigJsonPath,
        [Parameter(Mandatory = $true)]$Subsystems
    )

    $simConfig = Read-SimConfigDocument $SimConfigJsonPath
    $simConstantsDir = Join-Path (Get-Location) "src/main/java/frc/robot/constants/sim"
    New-Item -ItemType Directory -Force -Path $simConstantsDir | Out-Null

    $wantedFiles = @{}
    $written = @()

    foreach ($subsystem in @($Subsystems)) {
        $metadata = Get-SubsystemMetadata $subsystem
        $config = Get-SimConfigForSubsystem $simConfig $metadata.Id
        $type = Get-SimConfigType $config
        if ($type -eq "none") {
            continue
        }

        $fileName = "$($metadata.PascalName)SimConstants.java"
        $wantedFiles[$fileName] = $true
        $outputFile = Join-Path $simConstantsDir $fileName
        Set-Content -Path $outputFile -Value (New-SubsystemSimConstantsContent $subsystem $metadata $config) -Encoding ascii
        $written += $outputFile
    }

    if (Test-Path $simConstantsDir) {
        Get-ChildItem -Path $simConstantsDir -Filter "*SimConstants.java" -File | ForEach-Object {
            if ($_.Name -eq "GamePieceSimConstants.java") {
                return
            }
            $content = Get-Content -Path $_.FullName -Raw
            if ($content.Contains("Generated by PowerLib simulation tool") -and -not $wantedFiles.ContainsKey($_.Name)) {
                Remove-Item -LiteralPath $_.FullName -Force
                Write-Host "Deleted removed subsystem sim constants $($_.Name)"
            }
        }
    }

    return $written
}

