function Get-JavaConstantRows {
    param([Parameter(Mandatory = $true)][AllowEmptyString()][string]$Source)

    $masked = [regex]::Replace($Source, '/\*[\s\S]*?\*/|//[^\r\n]*|"""[\s\S]*?"""|"(?:\\[\s\S]|[^"\\])*"|''(?:\\[\s\S]|[^''\\])*''', {
        param($matchResult)
        return [regex]::Replace($matchResult.Value, '[^\r\n]', ' ')
    })
    $pattern = '(?:(@(?:frc\.powerlib\.tuning\.)?TunableConstant)\s+)?\bpublic\s+static\s+(?:final|volatile)\s+([\w.$<>?,\s\[\]]+?)\s+([A-Za-z_$][\w$]*)\s*='
    $customStart = $Source.IndexOf($CustomConstantsStartMarker)
    $customEnd = $Source.IndexOf($CustomConstantsEndMarker)
    foreach ($matchResult in [regex]::Matches($masked, $pattern)) {
        $prefix = $masked.Substring(0, $matchResult.Index)
        if (([regex]::Matches($prefix, '\{').Count - [regex]::Matches($prefix, '\}').Count) -ne 1) { continue }
        $expressionStart = $matchResult.Index + $matchResult.Length
        $nesting = 0
        $end = $expressionStart
        for (; $end -lt $masked.Length; $end++) {
            $char = $masked[$end]
            if ('([{'.Contains($char)) { $nesting++ }
            if (')]}'.Contains($char)) { $nesting-- }
            if ($char -eq ';' -and $nesting -eq 0) { break }
        }
        if ($end -eq $masked.Length) { throw "Missing semicolon for constant $($matchResult.Groups[3].Value)." }
        [pscustomobject]@{
            name = $matchResult.Groups[3].Value
            type = $matchResult.Groups[2].Value.Trim()
            value = $Source.Substring($expressionStart, $end - $expressionStart).Trim()
            custom = $customStart -ge 0 -and $matchResult.Index -gt $customStart -and $end -lt $customEnd
            tunable = $matchResult.Groups[1].Success
            start = $matchResult.Index
            end = $end + 1
        }
    }
}

