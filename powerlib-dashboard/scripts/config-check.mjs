import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
const result = await build({ entryPoints: [fileURLToPath(new URL("../src/features/config/subsystemValidation.ts", import.meta.url))], bundle: true, write: false, format: "esm", platform: "node" });
const { validateSubsystemStep, buildSubsystem } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString("base64")}`);
const utilities = await build({ entryPoints: [fileURLToPath(new URL("../src/features/subsystems/subsystemUtils.ts", import.meta.url))], bundle: true, write: false, format: "esm", platform: "node" });
const { createEmptySubsystemForm, subsystemToForm } = await import(`data:text/javascript;base64,${Buffer.from(utilities.outputFiles[0].contents).toString("base64")}`);
const form = { ...createEmptySubsystemForm(), name: "Intake", id: "intake" };
form.motors[0].id = "0";
for (let step = 0; step < 3; step++) assert.deepEqual(validateSubsystemStep(form, [], step), [], `Default configuration with CAN ID zero is valid at step ${step}`);
const subsystem = buildSubsystem(form);
assert.equal(subsystem.motors[0].id, 0);
assert.ok(validateSubsystemStep(form, [subsystem], 0).some(issue => issue.includes("name already exists")));
assert.ok(validateSubsystemStep({ ...form, name: "Vision" }, [], 0).some(issue => issue.includes("reserved")));
assert.ok(validateSubsystemStep({ ...form, name: "Intake Roller" }, [], 0).length);
assert.ok(validateSubsystemStep({ ...form, sensorToMechanism: "" }, [], 0).length);
assert.ok(validateSubsystemStep({ ...form, motors: [{ ...form.motors[0], id: "1.5" }] }, [], 1).length);
assert.ok(validateSubsystemStep({ ...form, motors: [{ ...form.motors[0], id: "" }] }, [], 1).length);
assert.ok(validateSubsystemStep({ ...form, motors: [form.motors[0], { ...form.motors[0], role: "follower" }] }, [], 1).some(issue => issue.includes("more than one motor")));
assert.ok(validateSubsystemStep(form, [subsystem], 1).some(issue => issue.includes("another subsystem")));
assert.ok(validateSubsystemStep({ ...form, kP: "NaN" }, [], 2).length);
assert.ok(validateSubsystemStep({ ...form, type: "absolutePosition" }, [], 1).some(issue => issue.includes("CANcoder")));
assert.ok(validateSubsystemStep({ ...form, type: "relativePosition", reverseSoftLimit: "2", forwardSoftLimit: "1" }, [], 1).length);
const existing = { ...subsystem, statorCurrentLimitAmps: 45, motionMagic: { ...subsystem.motionMagic, jerk: 9 } };
const editForm = subsystemToForm(existing, 0);
for (let step = 0; step < 3; step++) assert.deepEqual(validateSubsystemStep(editForm, [existing], step), [], "Editing does not conflict with its own name or CAN IDs");
const updated = buildSubsystem(editForm, existing);
assert.equal(updated.statorCurrentLimitAmps, 45);
assert.equal(updated.motionMagic.jerk, 9);
const changed = buildSubsystem(editForm, { ...existing, cancoder: { id: 5 }, absolutePosition: { units: "degrees" }, slowMotionMagic: { acceleration: 1 } });
assert.equal(changed.cancoder, undefined);
assert.equal(changed.absolutePosition, undefined);
assert.equal(changed.slowMotionMagic, undefined);
console.log("Config checks passed: required values, unique names/IDs, CAN validation, type-specific fields, edit preservation and type changes.");

const settingsBuild = await build({ entryPoints: [fileURLToPath(new URL("../src/features/dashboard/dashboardSettings.ts", import.meta.url))], bundle: true, write: false, format: "esm", platform: "node" });
const storage = new Map();
let storageFails = false;
globalThis.localStorage = { getItem: key => storage.get(key) ?? null,
  setItem: (key, value) => { if (storageFails) throw Error("Storage unavailable"); storage.set(key, value); } };
globalThis.window = new EventTarget();
const { dashboardSettingsKey, getDashboardSettings, saveFieldDimensions, subscribeDashboardSettings } = await import(`data:text/javascript;base64,${Buffer.from(settingsBuild.outputFiles[0].contents).toString("base64")}`);
storage.set(dashboardSettingsKey, JSON.stringify({ length: 16, width: 8, flip: true, urls: { front: "http://camera/stream" } }));
let notifications = 0;
const unsubscribe = subscribeDashboardSettings(() => notifications++);
assert.equal(getDashboardSettings().length, 16, "Existing display preferences are retained");
saveFieldDimensions({ length: 18, width: 9 });
assert.equal(notifications, 1, "Saving immediately notifies dashboard consumers");
assert.deepEqual(JSON.parse(storage.get(dashboardSettingsKey)), { length: 18, width: 9, flip: true, urls: { front: "http://camera/stream" } });
for (const length of [0, -1, NaN, Infinity]) assert.throws(() => saveFieldDimensions({ length, width: 9 }));
for (const width of [0, -1, NaN, Infinity]) assert.throws(() => saveFieldDimensions({ length: 18, width }));
storageFails = true;
assert.throws(() => saveFieldDimensions({ length: 20, width: 10 }));
assert.equal(getDashboardSettings().length, 18, "A storage failure must preserve the active settings");
storageFails = false;
storage.set(dashboardSettingsKey, JSON.stringify({ length: 20, width: 10 }));
const change = new Event("storage");
Object.defineProperty(change, "key", { value: dashboardSettingsKey });
window.dispatchEvent(change);
assert.equal(getDashboardSettings().length, 20, "Changes from another app window refresh dimensions");
unsubscribe();
console.log("Field settings checks passed: persistence, live updates, validation, preference preservation, storage failure and window synchronization.");
