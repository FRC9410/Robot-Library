function Read-SimConfigDocument {
    param([Parameter(Mandatory = $true)][string]$JsonPath)

    if (-not (Test-Path $JsonPath)) {
        return [pscustomobject]@{ drivetrain = $null; subsystems = [pscustomobject]@{} }
    }

    $raw = Get-Content -Path $JsonPath -Raw -Encoding utf8
    $parsed = $raw | ConvertFrom-Json
    $cfg = if (($parsed.PSObject.Properties.Name -contains "config") -and $null -ne $parsed.config) { $parsed.config } else { $parsed }

    $drivetrain = if (($cfg.PSObject.Properties.Name -contains "drivetrain") -and $null -ne $cfg.drivetrain) { $cfg.drivetrain } else { $cfg }
    $subsystems = if (($cfg.PSObject.Properties.Name -contains "subsystems") -and $null -ne $cfg.subsystems) { $cfg.subsystems } else { [pscustomobject]@{} }

    return [pscustomobject]@{
        drivetrain = $drivetrain
        subsystems = $subsystems
    }
}

function Get-SimConfigForSubsystem {
    param(
        [Parameter(Mandatory = $true)]$SimConfigDocument,
        [Parameter(Mandatory = $true)][string]$SubsystemId
    )

    $subsystems = $SimConfigDocument.subsystems
    $propertyNames = if ($null -ne $subsystems -and $null -ne $subsystems.PSObject -and $null -ne $subsystems.PSObject.Properties) {
        @($subsystems.PSObject.Properties | ForEach-Object { $_.Name })
    } else {
        @()
    }

    if ($null -eq $subsystems -or -not ($propertyNames -contains $SubsystemId)) {
        return $null
    }

    return $subsystems.$SubsystemId
}

function Get-SimConfigType {
    param($Config)

    if ($null -eq $Config) {
        return "none"
    }
    if (($Config.PSObject.Properties.Name -contains "type") -and -not [string]::IsNullOrWhiteSpace($Config.type)) {
        return $Config.type.ToString().ToLowerInvariant()
    }
    if (($Config.PSObject.Properties.Name -contains "enabled") -and $Config.enabled) {
        return "motor"
    }

    return "none"
}

