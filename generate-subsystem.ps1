$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$StateMachineStartMarker = "  // POWERLIB GENERATED SUBSYSTEMS START - DO NOT DELETE"
$StateMachineEndMarker = "  // POWERLIB GENERATED SUBSYSTEMS END - DO NOT DELETE"
$ConstantsStartMarker = "  // POWERLIB GENERATED CONSTANTS START - DO NOT DELETE"
$ConstantsEndMarker = "  // POWERLIB GENERATED CONSTANTS END - DO NOT DELETE"
$GeneratedFileMarker = "// Generated by PowerLib subsystem tool. Edit powerlib-subsystems.json, then run update."
$SubsystemIdMarkerPrefix = "// POWERLIB SUBSYSTEM ID: "
