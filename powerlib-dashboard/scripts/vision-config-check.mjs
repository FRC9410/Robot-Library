import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { configFixture } from "./config-fixture.mjs";
const {api, root, file} = await configFixture("vision-config");
const source = file("constants/VisionConstants.java");
let initial = await api.readVisionConfig(root);
const config = {...initial.vision,fovDegrees:63.3,imageWidth:640,imageHeight:480,limelights:[{name:"limelight-front"},{name:"limelight-back"}]};
await api.saveVisionConfig(root,config);
const saved = await api.readVisionConfig(root);
assert.deepEqual(saved.vision.limelights,config.limelights);
assert.equal(saved.vision.fovDegrees,63.3);
const before = await fs.readFile(source,"utf8");
for (const patch of [{limelights:[{name:"front"}]},{limelights:[{name:"limelight-Front"}]},{limelights:[{name:"limelight-front--camera"}]},{limelights:[config.limelights[0],config.limelights[0]]},{fovDegrees:180},{imageWidth:0},{imageHeight:2.5}]) await assert.rejects(api.saveVisionConfig(root,{...saved.vision,...patch}));
assert.equal(await fs.readFile(source,"utf8"),before);
await api.saveVisionConfig(root,{...saved.vision,limelights:[]});
assert.deepEqual((await api.readVisionConfig(root)).vision.limelights,[]);
assert.ok((await fs.readFile(source,"utf8")).includes("VisionHeadingInitializationConfig.DEFAULT"));
await assert.rejects(api.saveVisionConfig(root,config),/changed since/);
console.log("Vision source checks passed: camera list, shared dimensions, empty list, validation, stale revisions and preserved vision policy.");
